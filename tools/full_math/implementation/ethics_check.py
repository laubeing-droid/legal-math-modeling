# D124 — triggered duties by index scan, clearance by decision table
# ---------------------------------------------------------------------------

def check_D124(edges: Sequence[Tuple[str, str, str]],
               rules: Sequence[Tuple[str, str, bool]],
               claimed: dict) -> CheckReport:
    """Independent trigger scan: for every rule, scan the edge list by
    index for its trigger kind; clearance by a decision table over
    (waivable, state) instead of branch logic; the draft witness, the
    non-waivable panel rejection, the partner insufficiency and the
    panel clearance are all re-derived."""

    reasons: List[str] = []
    duties: List[Tuple[str, str]] = []
    idx = 0
    while idx < len(rules):
        rule = rules[idx]
        j = 0
        hit = False
        while j < len(edges):
            if edges[j][2] == rule[0]:
                hit = True
                break
            j += 1
        if hit:
            duties.append((rule[0], rule[1]))
        idx += 1
    if claimed.get("duties") != duties:
        reasons.append("triggered duties differ from the index scan")
    if claimed.get("duties_from_registry") is not True:
        reasons.append("every reported duty must come from the registry")
    for d in duties:
        k = 0
        seen = False
        while k < len(edges):
            if edges[k][2] == d[0]:
                seen = True
            k += 1
        if not seen:
            reasons.append("a reported trigger is not in the graph")

    def table_clears(waivable: bool, state: str) -> bool:
        # decision table rows: (waivable, state-shape, authority, result)
        rows = [
            (True, "draft", None, False),
            (False, "draft", None, False),
            (False, "granted", "ethicsPanel", False),
            (False, "granted", "managingPartner", False),
            (True, "granted", "ethicsPanel", True),
            (True, "granted", "managingPartner", False),
        ]
        if state == "draft":
            shape, auth = "draft", None
        elif state.startswith("granted:"):
            shape, auth = "granted", state.split(":", 1)[1]
        else:
            raise ValueError(state)
        for (w, s, a, res) in rows:
            if w == waivable and s == shape and a == auth:
                return res
        return False

    if claimed.get("draft_clears_nothing") is not (
            table_clears(False, "draft") is False
            and table_clears(True, "draft") is False):
        reasons.append("a draft must clear nothing")
    if claimed.get("nonwaivable_never_cleared") is not (
            table_clears(False, "granted:ethicsPanel") is False):
        reasons.append("a non-waivable conflict is never cleared")
    if claimed.get("partner_insufficient") is not (
            table_clears(True, "granted:managingPartner") is False):
        reasons.append("the managing partner cannot clear a waivable")
    if claimed.get("panel_clears_waivable") is not (
            table_clears(True, "granted:ethicsPanel") is True):
        reasons.append("the ethics panel clears a waivable conflict")
    if claimed.get("witness_duty_reported") is not (
            duties == [("concurrent-client", "disclose-and-screen")]
            or claimed.get("witness_duties")
            == [("concurrent-client", "disclose-and-screen")]):
        reasons.append("the concurrent-client duty witness differs")
    return CheckReport(not reasons, reasons)


