# D129 — verdicts by gate ladder, numbers by fresh Fraction folds
# ---------------------------------------------------------------------------

def check_D129(sources, conflicts, claims, claimed: dict) -> CheckReport:
    """Independent verification: a gate ladder (conflict → read-back →
    scope) instead of the reference's two-step branch; the numbers by
    fresh Fraction folds (sum by explicit accumulation, count by list
    length); the misused-citation, inflated-number and conflict-hold
    witnesses re-derived."""

    reasons: List[str] = []
    sources = {str(k): tuple(v) for k, v in sources.items()}
    conflicts = [tuple(c) for c in conflicts]

    def ladder(c):
        for (a, b) in conflicts:
            if c["source"] in (a, b):
                return "held"
        if c["source"] not in sources:
            return "failed"
        if c["prop"] not in sources[c["source"]]:
            return "failed"
        return "verified"

    for c in claims:
        expect = ladder(c)
        got = None
        for (p, v) in claimed.get("verdicts", []):
            if p == c["prop"]:
                got = v
        if got != expect:
            reasons.append(f"verdict for {c['prop']} differs from the"
                           " gate ladder")

    def own_sum(xs):
        acc = Fraction(0)
        for x in xs:
            acc += Fraction(x)
        return acc

    loss = {"prop": "total-loss", "source": "damages-table-7",
            "data": [F(100), F(250), F(150)], "op": "sum"}
    inflated = dict(loss, claimed=F(600))
    count = {"prop": "pending-count", "source": "docket-index-2026",
             "data": [F(1), F(1), F(1)], "op": "count"}
    if claimed.get("witness_loss_recompute") != own_sum(loss["data"]):
        reasons.append("loss recompute must be 500")
    if claimed.get("witness_loss_claimed") != F(500):
        reasons.append("the loss claim must be 500")
    if claimed.get("witness_inflated_recompute") != own_sum(
            inflated["data"]):
        reasons.append("inflated recompute must still be 500")
    if claimed.get("witness_inflated_claimed") != F(600):
        reasons.append("the inflated claim must be 600")
    if claimed.get("witness_inflated_fails") is not (
            own_sum(inflated["data"]) != F(600)):
        reasons.append("the inflated number must fail the recompute")
    if claimed.get("witness_count_recompute") != Fraction(
            len(count["data"])):
        reasons.append("count recompute must be 3")

    misused = {"prop": "total-loss", "source": "docket-index-2026",
               "data": [F(100), F(250), F(150)], "op": "sum"}
    if claimed.get("witness_misused_cite_ok") is not (
            misused["source"] in sources):
        reasons.append("the misused citation is real")
    if claimed.get("witness_misused_scope_fails") is not (
            misused["prop"] not in sources[misused["source"]]):
        reasons.append("the real source does not support the proposition")
    if claimed.get("witness_misused_fails") is not (
            ladder(misused) == "failed"):
        reasons.append("a real-but-unsupported citation must fail")
    table_conflict = [("damages-table-7", "affidavit-9")]
    # conflict-hold re-derivation, spelled out plainly:
    touches = any(loss["source"] in (a, b) for (a, b) in table_conflict)
    expect_held = "held" if touches else ladder(loss)
    if claimed.get("witness_conflict_holds") is not (expect_held == "held"):
        reasons.append("the unresolved conflict must hold the claim")
    if claimed.get("witness_conflict_not_verified") is not (
            expect_held != "verified"):
        reasons.append("a held claim is not verified")
    if claimed.get("witness_conflict_free_verified") is not (
            ladder(loss) == "verified"):
        reasons.append("with the conflict gone the claim verifies")
    return CheckReport(not reasons, reasons)


