# D125 — invariance by twin construction, rates by row counters
# ---------------------------------------------------------------------------

def check_D125(classifier, rows, claimed: dict) -> CheckReport:
    """Independent fairness audit: build each row's counterfactual twin
    by explicit tuple construction (not a helper), check the verdicts
    pairwise; group rates by flagged/size counters instead of filters;
    the tag separation by tag inspection; the Beta coverage by a fresh
    integer-parameter Bernstein sum (a different route than the
    reference's library CDF)."""

    reasons: List[str] = []
    rows = [tuple(r) for r in rows]
    invariance = True
    for r in rows:
        twin = ((not r[0]),) + tuple(r[1:])
        if classifier(twin) != classifier(r):
            invariance = False
    if claimed.get("invariance") is not invariance:
        reasons.append("invariance differs from the twin comparison")

    rates = {}
    for g in (True, False):
        flagged = 0
        size = 0
        for r in rows:
            if r[0] == g:
                size += 1
                if classifier(r):
                    flagged += 1
        if size == 0:
            raise ValueError("audited group is empty")
        rates[g] = Fraction(flagged, size)
    if claimed.get("rates") != rates:
        reasons.append("group rates differ from the row counters")

    # the leak witness re-derived inline: proxy-keyed classifier, four
    # rows leaked by proxy
    def proxy(row):
        return row[1] == "zip-17"

    leak_rows = [(True, "zip-17", 1), (True, "zip-17", 2),
                 (False, "zip-03", 3), (False, "zip-03", 4)]
    leak_inv = all(proxy(((not r[0]),) + tuple(r[1:])) == proxy(r)
                   for r in leak_rows)
    leak_true = Fraction(2, 2)
    leak_false = Fraction(0, 2)
    if claimed.get("leak_invariance") is not leak_inv:
        reasons.append("the leak witness must pass invariance")
    if claimed.get("leak_rate_true") != leak_true \
            or claimed.get("leak_rate_false") != leak_false:
        reasons.append("the leak witness rates must be 1 and 0")
    if claimed.get("leak_rates_differ") is not (leak_true != leak_false):
        reasons.append("the leak rates must differ")
    if claimed.get("leak_certs") != ["invariance"]:
        reasons.append("the leak audit issued only the invariance tag")
    if claimed.get("leak_full_claim") is not False:
        reasons.append("a single tag must not license the full claim")
    if claimed.get("single_tag_is_not_full") is not True:
        reasons.append("single-tag-is-not-full flag missing")

    # Beta coverage by a fresh Bernstein-form sum over j = α..α+β−1
    def own_cdf(a: int, b: int, x: Fraction) -> Fraction:
        if a < 1 or b < 1:
            raise ValueError("Beta parameters >= 1")
        if x <= 0:
            return Fraction(0)
        if x >= 1:
            return Fraction(1)
        m = a + b - 1
        # C(m, j) by multiplicative accumulation
        total = Fraction(0)
        c = 1
        # start at j = 0 and walk up, keeping the binomial live
        for j in range(0, m + 1):
            if j > 0:
                c = c * (m - j + 1) // j
            if j >= a:
                total += Fraction(c) * x ** j * (1 - x) ** (m - j)
        return total

    cov = claimed.get("beta_coverage", {})
    for g in (True, False):
        flagged = sum(1 for r in rows if r[0] == g and classifier(r))
        size = sum(1 for r in rows if r[0] == g)
        expect = own_cdf(1 + flagged, 1 + (size - flagged), Fraction(1, 2))
        got = cov.get(g)
        if _frac(got if got is not None else F(-1)) != expect:
            reasons.append(f"Beta coverage for group {g} differs from"
                           " the fresh Bernstein sum")
    return CheckReport(not reasons, reasons)


