"""Independent checker for the group-14/15 ethics, privacy, expression
reliability and US-law entries (D124-D134, W2-A batch B14).

ZERO sharing discipline (same as the B07/B13 siblings): this module does
NOT import ``ethics_ref`` — not its functions, not its constants, not
any helper.  Every check re-derives the contract semantics inline from
plain tuples, dicts, ints and Fractions, using different code paths than
the reference (membership by index scan, clearance by a decision table,
group rates by row counters instead of filters, decisions by
score-vector comparison instead of lexicographic walks, verdicts by a
gate ladder, assembly by label-set construction instead of early exit,
matching by row scans with position bookmarks, spans by manual bound
checks, classification by a two-column table instead of if-chains).  No
witness callback and no expected value generated by the main
implementation is ever trusted.

Lean contract: JurisLean.FullMath.Contracts.demand_D124 … demand_D134
(W2-A batch B14), first conjunct the registered components
JurisLean.FullMath.Evidence.step_rules_mono (D124-D130) and
JurisLean.FullMath.Probability.condition_incompatible_iff (D131-D134).
"""
from __future__ import annotations

from fractions import Fraction
from typing import List, Sequence, Tuple

F = Fraction


class CheckReport:
    __slots__ = ("ok", "reasons")

    def __init__(self, ok: bool, reasons: Sequence[str] = ()) -> None:
        self.ok = bool(ok)
        self.reasons = tuple(reasons)

    @classmethod
    def pass_(cls) -> "CheckReport":
        return cls(True)

    @classmethod
    def fail(cls, *reasons: str) -> "CheckReport":
        return cls(False, reasons)

    def __bool__(self) -> bool:
        return self.ok


def _frac(x) -> Fraction:
    if type(x) is not Fraction:
        raise TypeError(f"expected Fraction, got {type(x).__name__}")
    return x


