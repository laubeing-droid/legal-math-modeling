# D128 — decision by score-vector comparison, not lexicographic walk
# ---------------------------------------------------------------------------

def check_D128(premise: dict, claimed: dict) -> CheckReport:
    """Independent decision: score vectors compared under the declared
    order by explicit dimension lookup (dict tables, not option
    records); the unbeaten option found by pairwise sweep instead of a
    filter; the sensitivity and majority witnesses re-derived."""

    reasons: List[str] = []
    opts = [("full-privacy", 5, 2), ("fast-track", 2, 5),
            ("balanced-veil", 5, 4)]

    def vec(option):
        return {"privacy": option[1], "efficiency": option[2]}

    def strict_better(order, a, b):
        for dim in order:
            va, vb = vec(a).get(dim, 0), vec(b).get(dim, 0)
            if va > vb:
                return True
            if vb > va:
                return False
        return False

    def pick(order):
        if not order:
            return None
        for a in opts:
            beaten = False
            for b in opts:
                if b[0] != a[0] and strict_better(order, b, a):
                    beaten = True
                    break
            if not beaten:
                return a
        return None

    if premise.get("kind") == "declaredValue":
        expect = pick(list(premise.get("order", [])))
    else:
        expect = None
    got = claimed.get("decision")
    norm_got = tuple(got) if got is not None else None
    norm_expect = tuple(expect) if expect is not None else None
    if norm_got != norm_expect:
        reasons.append("decision differs from the score-vector pick")

    priv_pick = pick(["privacy", "efficiency"])
    eff_pick = pick(["efficiency", "privacy"])
    if claimed.get("witness_privacy_pick_name") != priv_pick[0]:
        reasons.append("privacy-first must pick balanced-veil")
    if claimed.get("witness_efficiency_pick") != eff_pick[0]:
        reasons.append("efficiency-first must pick fast-track")
    if claimed.get("sensitivity") is not (priv_pick[0] != eff_pick[0]):
        reasons.append("the two orders must decide differently")
    if claimed.get("empty_order_no_decision") is not (pick([]) is None):
        reasons.append("no declared order means no decision")
    majority = {"kind": "majorityPreference",
                "order": ["efficiency", "privacy"]}
    if claimed.get("majority_premise_no_decision") is not (
            majority["kind"] != "declaredValue" or pick([]) is None):
        reasons.append("a majority-preference premise licenses nothing")
    if claimed.get("decision_within_options") is not (
            expect is None or tuple(expect) in [tuple(o) for o in opts]):
        reasons.append("the decision must stay within the options")
    return CheckReport(not reasons, reasons)


