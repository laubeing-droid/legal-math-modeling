# D130 — assembly by label-set construction
# ---------------------------------------------------------------------------

def check_D130(conclusions, claimed: dict) -> CheckReport:
    """Independent assembly: collect the scenario labels into a set —
    exactly one label assembles conditionally with that label, anything
    else (zero or many) is rejected; both witnesses re-derived."""

    reasons: List[str] = []
    conclusions = [tuple(c) for c in conclusions]
    labels = []
    for (scen, _concl) in conclusions:
        if scen not in labels:
            labels.append(scen)
    if len(labels) == 1:
        expect = {"outcome": "conditional", "scenario": labels[0]}
    else:
        expect = {"outcome": "rejected", "scenario": None}
    if claimed.get("outcome") != expect["outcome"] \
            or claimed.get("scenario") != expect["scenario"]:
        reasons.append("assembly differs from the label-set verdict")

    kappa1 = [("kappa-1", "motion-to-dismiss-denied"),
              ("kappa-1", "liability-found")]
    cherry = [("kappa-1", "liability-found"),
              ("kappa-2", "damages-maximized")]
    if claimed.get("witness_single_scenario") is not (
            len({c[0] for c in kappa1}) == 1):
        reasons.append("the single-scenario set must assemble")
    if claimed.get("witness_cherry_picked_rejected") is not (
            len({c[0] for c in cherry}) == 2):
        reasons.append("the cherry-picked set must be rejected")
    if claimed.get("no_unconditional_outcome") is not True:
        reasons.append("there is no unconditional outcome form")
    return CheckReport(not reasons, reasons)


