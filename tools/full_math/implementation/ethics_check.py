# D127 — statutory coverage by row bookmark, advisory typing by label
# ---------------------------------------------------------------------------

def check_D127(items, done, claimed: dict) -> CheckReport:
    """Independent coverage: walk the register with a row bookmark,
    fail on the first statutory item missing from the done list (no
    filter); the advisory readout must carry the advisory label on every
    row; the two-of-three witness re-derived."""

    reasons: List[str] = []
    items = [tuple(i) for i in items]
    done = [str(d) for d in done]
    covered = True
    missing: List[str] = []
    row = 0
    while row < len(items):
        item, kind = items[row]
        if kind == "statutory":
            found = False
            k = 0
            while k < len(done):
                if done[k] == item:
                    found = True
                k += 1
            if not found:
                covered = False
                missing.append(item)
        row += 1
    if claimed.get("covered") is not covered:
        reasons.append("coverage differs from the row bookmark walk")
    if claimed.get("missing_statutory") != missing:
        reasons.append("missing statutory items differ")

    for p in claimed.get("advisory", []):
        if tuple(p)[1] != "advisory":
            reasons.append("best-practice rows must stay advisory-typed")
    if claimed.get("advisory_typed") is not True:
        reasons.append("advisory-typed flag missing")

    register = [("conflict-mineral-report", "statutory"),
                ("forced-labor-disclosure", "statutory"),
                ("ghg-emissions", "statutory"),
                ("supplier-diversity", "bestPractice"),
                ("open-source-policy", "bestPractice")]
    gap = ["conflict-mineral-report", "forced-labor-disclosure",
           "supplier-diversity", "open-source-policy"]
    full = gap[:2] + ["ghg-emissions"] + gap[2:]
    gap_covered = True
    for (item, kind) in register:
        if kind == "statutory" and item not in gap:
            gap_covered = False
    full_covered = True
    for (item, kind) in register:
        if kind == "statutory" and item not in full:
            full_covered = False
    if claimed.get("witness_gap_fails") is not (gap_covered is False):
        reasons.append("the two-of-three filing must fail")
    if claimed.get("witness_gap_done_count") is not len(gap):
        reasons.append("the witness filing has four done entries")
    if claimed.get("witness_optional_cannot_compensate") is not (
            gap_covered is False
            and sum(1 for (i, k) in register
                    if k == "bestPractice" and i in gap) == 2):
        reasons.append("two optional items cannot compensate the"
                       " statutory gap")
    if claimed.get("witness_full_covers") is not (full_covered is True):
        reasons.append("the full filing must cover")
    if claimed.get("witness_full_advisory") != [
            ("supplier-diversity", "advisory"),
            ("open-source-policy", "advisory")]:
        reasons.append("the full-filing advisory readout differs")
    return CheckReport(not reasons, reasons)


