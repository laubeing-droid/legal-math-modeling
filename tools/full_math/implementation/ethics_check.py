# D131 — private action by cite-class table
# ---------------------------------------------------------------------------

def check_D131(fragment, claimed: dict) -> CheckReport:
    """Independent scan: classify each cite into pathway/right/other by
    a class table, then the determination = any pathway row; the
    disjointness by cite-set intersection; the three fragments
    re-derived."""

    reasons: List[str] = []
    fragment = [tuple(p) for p in fragment]
    pathways = []
    rights = []
    for (cite, kind) in fragment:
        if kind == "privateAction":
            pathways.append(cite)
        elif kind == "substantiveRight":
            rights.append(cite)
    if claimed.get("has_private_action") is not (len(pathways) > 0):
        reasons.append("the determination differs from the class table")
    if claimed.get("pathways_within_fragment") is not all(
            p in [c for (c, _k) in fragment] for p in pathways):
        reasons.append("pathways must be found inside the fragment")
    if claimed.get("types_disjoint") is not (
            not (set(pathways) & set(rights))):
        reasons.append("a cite cannot be both pathway and right")

    prohibition = [("§5(a)(1)", "prohibition")]
    right_ban = [("§5(a)(1)", "prohibition"), ("§4(b)", "substantiveRight")]
    explicit = [("§4(b)", "substantiveRight"), ("§4(c)", "privateAction")]
    if claimed.get("witness_prohibition_only") is not (
            len([1 for (_c, k) in prohibition if k == "privateAction"]) == 0):
        reasons.append("a prohibition alone yields no private action")
    if claimed.get("witness_right_plus_ban") is not (
            len([1 for (_c, k) in right_ban if k == "privateAction"]) == 0):
        reasons.append("prohibition plus rights still yields none")
    if claimed.get("witness_explicit_pathway") is not (
            len([1 for (_c, k) in explicit if k == "privateAction"]) > 0):
        reasons.append("the explicit pathway fragment must yield one")
    if claimed.get("witness_pathway_cite") != "§4(c)":
        reasons.append("the pathway cite witness differs")
    return CheckReport(not reasons, reasons)


