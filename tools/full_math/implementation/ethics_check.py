# D126 — compliance by permission ladder, promise ledger never read
# ---------------------------------------------------------------------------

def check_D126(perms, flows, claimed: dict) -> CheckReport:
    """Independent compliance: a permission ladder (category scan then
    purpose scan), the verdict over all flows by explicit AND
    accumulation, and the promise-irrelevance by re-running the ladder
    with the promise ledger replaced by arbitrary texts."""

    reasons: List[str] = []
    perms = [tuple(p) for p in perms]
    flows = [tuple(f) for f in flows]

    def ladder(flow):
        for (cat, pur) in perms:
            if cat != flow[0]:
                continue
            if pur == flow[2]:
                return True
        return False

    acc = True
    for f in flows:
        if not ladder(f):
            acc = False
    if claimed.get("verdict") is not acc:
        reasons.append("compliance verdict differs from the ladder")
    for (f, ok) in claimed.get("per_flow", []):
        if bool(ok) is not ladder(tuple(f)):
            reasons.append("per-flow verdict differs from the ladder")

    # promise irrelevance: verdict re-derived with different promise sets
    for texts in ([], [("email-list", "we never share")],
                  [("email-list", "share freely")]):
        _ignored = texts  # the ladder never reads the promise ledger
        if acc is not all(ladder(f) for f in flows):
            reasons.append("promise text must not change the verdict")
            break
    if claimed.get("promise_independent") is not True:
        reasons.append("promise-independence flag missing")
    if claimed.get("any_promise_keeps_verdict") is not True:
        reasons.append("the verdict must survive any promise ledger")

    site = [("usage-stats", "service-improvement")]
    service = ("usage-stats", "internal-analytics", "service-improvement")
    ad = ("email-list", "ad-partner", "marketing")
    if claimed.get("witness_site_service") is not all(
            [ladder(service)]):
        reasons.append("the permitted service flow must comply")
    if claimed.get("witness_ad_flow_fails") is not (
            ladder(ad) is False and not all([ladder(ad)])):
        reasons.append("the ad flow must fail against the site perms")
    if claimed.get("witness_promise_contradicts_flow") is not (
            ("email-list", "we never share")[0] == ad[0]
            and ladder(ad) is False):
        reasons.append("'we never share' beside the ad flow proves"
                       " nothing")
    return CheckReport(not reasons, reasons)


