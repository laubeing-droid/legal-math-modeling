# D132 — match by row scan with holding/key/word bookmark checks
# ---------------------------------------------------------------------------

def check_D132(question, qkeys, qwords, candidates, claimed: dict) -> CheckReport:
    """Independent match: scan the candidate rows, bookmark the first
    row passing holding-status + key-containment + word-overlap (three
    explicit checks, no conjunction chains); the dictum witness
    re-derived; certificates never transferable."""

    reasons: List[str] = []
    expect = None
    for c in candidates:
        holding_ok = c.get("isHolding") is True
        key_ok = c.get("issueKey") in qkeys
        word_ok = False
        for w in c.get("words", ()):
            if w in qwords:
                word_ok = True
        if holding_ok and key_ok and word_ok:
            expect = {"cand": c["id"], "question": question,
                      "transferable": False}
            break
    got = claimed.get("certificate")
    if got != expect:
        reasons.append("match certificate differs from the row scan")
    if got is not None and got.get("transferable") is not False:
        reasons.append("certificates must stay non-transferable")
    if claimed.get("matched_holding_only") is not True:
        reasons.append("only core holdings may match")
    if claimed.get("certificate_not_transferable") is not True:
        reasons.append("non-transferable flag missing")

    dictum = {"id": "dictum-preemption-aside", "isHolding": False,
              "issueKey": "federal-preemption",
              "words": ("preempt", "state-law", "aside")}
    word_overlap = any(w in qwords for w in dictum["words"])
    if claimed.get("witness_dictum_similar") is not word_overlap:
        reasons.append("the dictum shares keywords with the question")
    if claimed.get("witness_dictum_not_holding") is not (
            dictum["isHolding"] is False):
        reasons.append("the dictum is not a holding")
    if claimed.get("witness_dictum_only_no_match") is not (
            dictum["isHolding"] is not True):
        reasons.append("a dictum-only pool must yield no match")
    if claimed.get("witness_pool_certificate") != {
            "cand": "holding-preemption", "question": question,
            "transferable": False}:
        reasons.append("the pool certificate witness differs")
    return CheckReport(not reasons, reasons)


# ---------------------------------------------------------------------------
# D133 — extraction by bound-checked row walks
# ---------------------------------------------------------------------------

def check_D133(segment, claimed: dict) -> CheckReport:
    """Independent extraction: walk the mention rows, keep the person
    key iff start ≤ end ≤ length (manual bound checks, no helper); the
    two-plaintiff, merged-name, first-only and ghost witnesses
    re-derived."""

    reasons: List[str] = []
    seg_len = int(segment["len"])
    mentions = [tuple(m) for m in segment["mentions"]]
    extracted = []
    for (person, st, en) in mentions:
        if st <= en and en <= seg_len:
            extracted.append(person)
    if claimed.get("extracted") != extracted:
        reasons.append("extraction differs from the bound-checked walk")
    if claimed.get("each_backed_by_span") is not True:
        reasons.append("every extracted plaintiff needs a valid span")

    witness_seg = {"len": 120, "mentions": [("Alice Chen", 14, 24),
                                            ("Bob Diaz", 60, 67)]}
    witness = []
    for (person, st, en) in witness_seg["mentions"]:
        if st <= en and en <= witness_seg["len"]:
            witness.append(person)
    if claimed.get("witness_both_extracted") is not (
            witness == ["Alice Chen", "Bob Diaz"]):
        reasons.append("both co-plaintiffs must be extracted")
    if claimed.get("witness_separate_keys") is not (
            len(witness) == 2 and witness[0] != witness[1]):
        reasons.append("the plaintiff keys stay separate")
    if claimed.get("witness_merged_never_enters") is not (
            "Alice Chen and Bob Diaz" not in witness):
        reasons.append("the merged name never enters the extraction")
    if claimed.get("witness_first_only_is_not_complete") is not (
            ["Alice Chen"] != witness):
        reasons.append("the first name alone is not the full set")
    ghost = [("Ghost", 8, 12)]
    ghost_out = []
    for (person, st, en) in ghost:
        if st <= en and en <= 10:
            ghost_out.append(person)
    if claimed.get("witness_ghost_excluded") is not (ghost_out == []):
        reasons.append("the out-of-segment span must be excluded")
    return CheckReport(not reasons, reasons)


# ---------------------------------------------------------------------------
# D134 — classification by two-column table, causation bridge absent
# ---------------------------------------------------------------------------

def check_D134(passages, claimed: dict) -> CheckReport:
    """Independent classification: a two-column comparison table (stat
    vs direct hits) instead of the reference's if-chain; the do-effect
    bridge re-derived as a constant-None table (structurally absent);
    the Beta label confidence by a fresh closed-form Bernoulli sum."""

    reasons: List[str] = []
    passages = [tuple(p) for p in passages]

    def label(stat, direct):
        if stat > 0 and stat > direct:
            return "statistical"
        if direct > 0 and direct > stat:
            return "directEvidence"
        return "neither"

    for (p, got) in claimed.get("labels", []):
        if got != label(int(p[0]), int(p[1])):
            reasons.append(f"classification of {p} differs from the"
                           " two-column table")
    if claimed.get("witness_statistical") is not (label(3, 0)
                                                  == "statistical"):
        reasons.append("(3,0) must classify statistical")
    if claimed.get("witness_direct") is not (label(0, 2)
                                             == "directEvidence"):
        reasons.append("(0,2) must classify directEvidence")
    if claimed.get("witness_neither") is not (label(1, 1) == "neither"):
        reasons.append("(1,1) must classify neither")

    bridge = claimed.get("do_bridge", {})
    for k in ("statistical", "directEvidence", "neither"):
        if bridge.get(k) is not None:
            reasons.append(f"the causation bridge must be absent for {k}")
    if claimed.get("no_do_conclusion_for_any_label") is not True:
        reasons.append("no label may generate a do-effect conclusion")
    if claimed.get("no_do_conclusion_for_statistical_hit") is not True:
        reasons.append("a statistical hit is not a causal identification")

    # fresh Beta(4,1) complement at x = 1/2 (the reference feeds the
    # statistical passage's 3-of-3 hits into the (1,1) prior):
    # P(p > 1/2) = Σ_{j=0}^{3} C(4,j) x^j (1-x)^{4-j} = 15/16
    x = Fraction(1, 2)
    expect_conf = Fraction(0)
    binom = 1
    for j in range(0, 4):
        if j > 0:
            binom = binom * (4 - j + 1) // j
        expect_conf += Fraction(binom) * x ** j * (1 - x) ** (4 - j)
    if claimed.get("beta_confidence_statistical") != expect_conf:
        reasons.append("the statistical label confidence differs from"
                       " the fresh binomial sum")
    if claimed.get("beta_confidence_is_fraction") is not True:
        reasons.append("the label confidence must be an exact Fraction")
    return CheckReport(not reasons, reasons)
