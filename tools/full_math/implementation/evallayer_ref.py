"""Evaluation-layer reference for needles 10-14 (plan section 5, appendix I:764-768).

Z1 audit gap group G1 (docs/full-math/NEEDLE_STRENGTH_AUDIT.md, needles 10/11/12/13/14):
the old deliveries restated the three-family rule anchor (AdjudicationBridge
rounds/mem_rounds_fst_fires); the staged evaluation fragment of main-text section 5
(card generation -> reason licensing -> attack certificates -> proof standard ->
final burden -> disposition) never entered the carrier.  This module is that
fragment:

- LegalDerives.card    (section 5.3.1): a card derives only from an ADMITTED,
  in-frame evidence item with a named reason (reason != 0).
- LegalDerives.attack  (section 5.3.6): an attack certificate derives only if it
  is in the frame's attack table, both endpoints are frame reasons, and it
  carries a non-zero material anchor (actual defeat witness; "not adopted" is
  not an attack).
- LegalDerives.standard(=CivilHigh, section 5.3.3): an in-extension licensed
  strong reason exists AND every live material counter is out.
- LegalDerives.final   (section 5.4 independent finalization table):
  Pos = Ready & E & !B, Neg = Ready & (B | (F & exists necessary element with
  claimant burden and not established)).
- ExhaustionRec carries the Need component as an explicit STRUCTURAL record
  (need items with pending kind + no-statutory-alternative bit), per the main
  text's public correction; undetermined iff Exhausted4 & Need & !Pos & !Neg;
  without Need a no-binary snapshot reads as a norm disposal gap (None), never
  as undetermined.
- BurdenInput is an independent input channel: apply_burden_input writes ONLY
  the proof-opportunity bit; the argument layer (materials/cards/reasons/
  attacks/accepted) is untouched.
- GenInput binds the record-truth side and the evaluation side to ONE input
  (needle 13); the evaluation is blind to the ontic-truth component.

Lean contract: proofs/lean/juris_lean/JurisLean/Seams/UnifiedEvalLayer.lean
(namespace JurisLean.Seams.UnifiedEvalLayer).  Independent checker:
tools/full_math/implementation/evallayer_check.py (shares only the frozen
carriers, re-implements every predicate inline).
"""
from __future__ import annotations

from dataclasses import dataclass, replace
from enum import Enum
from typing import Dict, FrozenSet, Iterable, List, Optional, Tuple


# ---------------------------------------------------------------------------
# Frozen carriers (section 5.3.1 / 5.3.2 / 5.3.6 / 5.4)
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class EvidenceItem:
    """Evaluation material excerpt (5.3.1): source identity is independent;
    `admitted` = admitted and cross-examined / directly adoptable by law."""

    evidence_id: int
    source_id: int
    content_claim: int
    admitted: bool


@dataclass(frozen=True)
class FactCard:
    """Local fact card Card(e, k, v, reason, source) (5.3.1): k ranges only over
    single-evidence or specific evidence-pair properties."""

    card_id: int
    from_evidence: int
    prop_key: int
    value: bool
    reason: int


@dataclass(frozen=True)
class ReasonNode:
    """Reason node r = (claim, polarity, kind, leaves, warrant) (5.3.2):
    `strong` = StrongBasis bit generated by a named sufficiency license
    (W-STRONG / S1-S6); `leaves` are card leaves."""

    reason_id: int
    claim: int
    polarity: bool
    strong: bool
    leaves: Tuple[int, ...]
    warrant: int


@dataclass(frozen=True)
class AttackCert:
    """Attack certificate (5.3.6 items 3/4): named material anchor required;
    anchor 0 = anchorless "not adopted" pseudo-certificate, never derives."""

    attack_id: int
    attacker: int
    target: int
    material_anchor: int


class PendingKind(Enum):
    """Need component kind (section 5.4 public correction)."""

    NOT_YET_OBTAINED = "not_yet_obtained"    # 尚未取得
    PRIOR_PENDING = "prior_pending"          # 先决未定


@dataclass(frozen=True)
class NeedItem:
    """Need component: an item lawfully recorded as not-yet-obtained /
    prior-pending with no statutory alternative — a structural record, not a
    missing-premise Bool."""

    item_id: int
    kind: PendingKind
    no_alternative: bool


@dataclass(frozen=True)
class RuleEntry:
    """Rule-family entry (Exhausted4 component): applied derivation OR at
    least one statutory defeat witness."""

    rule_id: int
    applied: bool
    defeat_witness: Optional[int]


@dataclass(frozen=True)
class ExhaustionRec:
    """Exhaustion record WITH the Need component (audit gap: Need enters the
    record structurally)."""

    burden: Tuple[RuleEntry, ...]
    presumption: Tuple[RuleEntry, ...]
    obstruction: Tuple[RuleEntry, ...]
    terminal: Tuple[RuleEntry, ...]
    need: Tuple[NeedItem, ...]


EMPTY_EXH = ExhaustionRec((), (), (), (), ())


@dataclass(frozen=True)
class Frame:
    """Evaluation snapshot: finite presentation of materials/cards/reasons/
    attack certificates + accepted set of the complete extension E + program
    and burden bits + per-question exhaustion record."""

    materials: Tuple[EvidenceItem, ...]
    cards: Tuple[FactCard, ...]
    reasons: Tuple[ReasonNode, ...]
    attacks: Tuple[AttackCert, ...]
    accepted: Tuple[int, ...]
    ready: FrozenSet[int]            # {q | Ready(q)}
    proof_closed: FrozenSet[int]     # {q | F(q)}: proof opportunity closed
    barred: FrozenSet[int]           # {q | B(q)}: named bar/extinction/defence
    elements: Dict[int, Tuple[int, ...]]   # necessary elements per question
    burden_on_claimant: FrozenSet[int]     # {e | persuasion burden on claimant}
    exhaustion: Dict[int, ExhaustionRec]

    def is_ready(self, q: int) -> bool:
        return q in self.ready

    def f_closed(self, q: int) -> bool:
        return q in self.proof_closed

    def is_barred(self, q: int) -> bool:
        return q in self.barred

    def elems(self, q: int) -> Tuple[int, ...]:
        return self.elements.get(q, ())

    def burden_on(self, e: int) -> bool:
        return e in self.burden_on_claimant

    def exh(self, q: int) -> ExhaustionRec:
        return self.exhaustion.get(q, EMPTY_EXH)


def reason_ids(fr: Frame) -> Tuple[int, ...]:
    return tuple(r.reason_id for r in fr.reasons)


# ---------------------------------------------------------------------------
# Stage constructions: LegalDerives (each independent, each sound)
# ---------------------------------------------------------------------------


def legal_derives_card(fr: Frame, c: FactCard) -> bool:
    """Card construction (5.3.1): in table + generated from an ADMITTED
    in-frame evidence item + named reason."""

    ev_ok = any(
        e.admitted and e.evidence_id == c.from_evidence
        for e in fr.materials)
    return c in fr.cards and ev_ok and c.reason != 0


def legal_derives_attack(fr: Frame, a: AttackCert) -> bool:
    """Attack construction (5.3.6): in attack table + both endpoints frame
    reasons + non-zero material anchor."""

    rids = set(reason_ids(fr))
    return (a in fr.attacks and a.attacker in rids and a.target in rids
            and a.material_anchor != 0)


def reason_licensed(fr: Frame, rn: ReasonNode) -> bool:
    """Reason licensing (5.3.2): strong bit + every leaf is a derivable card."""

    if not rn.strong:
        return False
    by_id = {c.card_id: c for c in fr.cards}
    for leaf in rn.leaves:
        c = by_id.get(leaf)
        if c is None or not legal_derives_card(fr, c):
            return False
    return True


def strong_for(fr: Frame, q: int, pol: bool, r: int) -> bool:
    """StrongBasis for atom (q, pol): a licensed in-frame reason with that
    claim and polarity."""

    return any(
        rn.reason_id == r and reason_licensed(fr, rn)
        and rn.claim == q and rn.polarity == pol
        for rn in fr.reasons)


def material_counter(fr: Frame, q: int, r: int) -> bool:
    """Same-identity counter role (5.3.6 item 1): the material counter to q is
    exactly the strong reason of the opposite atom."""

    return strong_for(fr, q, False, r)


def in_ext(fr: Frame, r: int) -> bool:
    return r in fr.accepted


def out_ext(fr: Frame, r: int) -> bool:
    """Out_E: an anchored attack certificate whose attacker is accepted."""

    return any(
        a.target == r and a.material_anchor != 0 and a.attacker in fr.accepted
        for a in fr.attacks)


def undec_ext(fr: Frame, r: int) -> bool:
    return not in_ext(fr, r) and not out_ext(fr, r)


def live_ext(fr: Frame, r: int) -> bool:
    """Live: In or Undec (never infer Out from 'not in In')."""

    return in_ext(fr, r) or undec_ext(fr, r)


def conflict_free(fr: Frame) -> bool:
    """Extension conflict-freedom: accepted reasons are not actually defeated."""

    return all(not out_ext(fr, r) for r in fr.accepted)


def civil_high(fr: Frame, q: int) -> bool:
    """CivilHigh (5.3.3): in-extension licensed strong reason + every live
    material counter is out."""

    if not any(strong_for(fr, q, True, r) and in_ext(fr, r) for r in reason_ids(fr)):
        return False
    for s in reason_ids(fr):
        if material_counter(fr, q, s) and live_ext(fr, s) and not out_ext(fr, s):
            return False
    return True


def civil_high_neg(fr: Frame, q: int) -> bool:
    """CivilHigh instantiated on the negative atom."""

    if not any(strong_for(fr, q, False, r) and in_ext(fr, r) for r in reason_ids(fr)):
        return False
    for s in reason_ids(fr):
        if strong_for(fr, q, True, s) and live_ext(fr, s) and not out_ext(fr, s):
            return False
    return True


def legal_derives_standard(fr: Frame, q: int) -> bool:
    return civil_high(fr, q)


def all_elements_established(fr: Frame, q: int) -> bool:
    return all(civil_high(fr, e) for e in fr.elems(q))


def pos_outcome(fr: Frame, q: int) -> bool:
    """Pos(q) = Ready & E & !B (5.4 independent finalization table)."""

    return fr.is_ready(q) and all_elements_established(fr, q) and not fr.is_barred(q)


def neg_outcome(fr: Frame, q: int) -> bool:
    """Neg(q) = Ready & (B | (F & exists necessary element with claimant
    burden and not established)) (5.4)."""

    if not fr.is_ready(q):
        return False
    if fr.is_barred(q):
        return True
    if not fr.f_closed(q):
        return False
    return any(
        fr.burden_on(e) and not civil_high(fr, e)
        for e in fr.elems(q))


def legal_derives_final(fr: Frame, q: int) -> bool:
    return pos_outcome(fr, q) or neg_outcome(fr, q)


# ---------------------------------------------------------------------------
# Exhaustion with the structural Need component (needle 12)
# ---------------------------------------------------------------------------


def entry_resolved(e: RuleEntry) -> bool:
    return e.applied or e.defeat_witness is not None


def family_resolved(entries: Iterable[RuleEntry]) -> bool:
    return all(entry_resolved(e) for e in entries)


def exhausted4(fr: Frame, q: int) -> bool:
    rec = fr.exh(q)
    return (family_resolved(rec.burden) and family_resolved(rec.presumption)
            and family_resolved(rec.obstruction) and family_resolved(rec.terminal))


def need_holds(fr: Frame, q: int) -> bool:
    return any(it.no_alternative for it in fr.exh(q).need)


ESTABLISHED = "established"
NOT_ESTABLISHED = "notEstablished"
UNDETERMINED = "undetermined"
GAP = None  # norm disposal gap: no binary finalization and no undetermined license


def classify(fr: Frame, q: int) -> str:
    """Four-way classification (5.4/5.5): pos/neg/undetermined/gap.  The gap
    is NOT a judgment value — the undetermined definition is not stretched to
    swallow it."""

    if pos_outcome(fr, q):
        return "pos"
    if neg_outcome(fr, q):
        return "neg"
    if exhausted4(fr, q) and need_holds(fr, q):
        return "undet"
    return "gap"


def final_judgment(fr: Frame, q: int) -> Optional[str]:
    kind = classify(fr, q)
    if kind == "pos":
        return ESTABLISHED
    if kind == "neg":
        return NOT_ESTABLISHED
    if kind == "undet":
        return UNDETERMINED
    return GAP


def covered_fragment(fr: Frame, q: int) -> bool:
    """Complete termination fragment coverage (5.4): must-evaluate (Ready+F)
    + every element covered by the claimant burden path (read from the actual
    program/burden tables, not an external 'coverage' bit)."""

    return (fr.is_ready(q) and fr.f_closed(q)
            and all(fr.burden_on(e) for e in fr.elems(q)))


