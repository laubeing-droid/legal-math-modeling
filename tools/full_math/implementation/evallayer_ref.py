# Burden input channel (needle 14): independent, argument-layer untouched
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class BurdenInput:
    """Statutory burden input: named identity + statutory basis + target
    question + proof-closure bit.  Not a re-reading of the argument layer."""

    input_id: int
    statutory_basis: int
    on_question: int
    closes_proof: bool


def apply_burden_input(fr: Frame, bi: BurdenInput) -> Frame:
    """Write ONLY the proof-opportunity bit for the target question."""

    closed = set(fr.proof_closed)
    if bi.closes_proof:
        closed.add(bi.on_question)
    else:
        closed.discard(bi.on_question)
    return replace(fr, proof_closed=frozenset(closed))


# ---------------------------------------------------------------------------
# GenInput: one input generates both the record-truth side and the eval side
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class GenInput:
    frame: Frame
    focus: int
    ontic_truth: bool            # R component; the evaluation never reads it


def gen_truth_judgment(g: GenInput) -> Optional[Tuple[bool, str]]:
    j = final_judgment(g.frame, g.focus)
    if j is None:
        return None
    return (g.ontic_truth, j)


