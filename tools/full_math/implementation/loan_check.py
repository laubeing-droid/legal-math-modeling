"""Independent checker for the group-06 loan/guarantee entries.

ZERO sharing discipline (stricter than the sibling checkers): this
module does NOT import ``loan_ref`` — not its functions, not its data
classes, and not the shared ``quantledger_ref`` surface either.  Every
check re-derives the contract semantics inline from plain tuples,
dicts and Fractions, using different code paths than the reference
(index-walking allocations instead of the v2 waterfall, direct division
instead of Fraction ratio multiplication, explicit branch tables
instead of dict lookups).  The reference's outputs are only ever
compared against these independently derived expectations; no witness
callback and no expected value generated by the main implementation is
ever trusted.

Lean contract: JurisLean.FullMath.Contracts.demand_D047 … demand_D056
(W2-A batch B06), over the shared carrier
JurisLean.Seams.UnifiedQuantLedger.
"""
from __future__ import annotations

from fractions import Fraction
from typing import Dict, List, Sequence, Tuple

F = Fraction


class CheckReport:
    __slots__ = ("ok", "reasons")

    def __init__(self, ok: bool, reasons: Sequence[str] = ()) -> None:
        self.ok = bool(ok)
        self.reasons = tuple(reasons)

    @classmethod
    def pass_(cls) -> "CheckReport":
        return cls(True)

    @classmethod
    def fail(cls, *reasons: str) -> "CheckReport":
        return cls(False, reasons)

    def __bool__(self) -> bool:
        return self.ok


def _frac(x) -> Fraction:
    if type(x) is not Fraction:
        raise TypeError(f"expected Fraction, got {type(x).__name__}")
    return x


# ---------------------------------------------------------------------------
# D047 — delivery fact / discharge fact, re-derived by direct branching
# ---------------------------------------------------------------------------

def check_D047(delivered: bool, ident: int, principal: Fraction,
               payments: Sequence[Fraction], claimed: dict) -> CheckReport:
    """Independent re-derivation: the booked amount is the principal
    only when delivered (direct branch, no ledger machinery), the end
    balance walks the payments one by one against the single amount,
    discharge ⇔ paid covers booked, and a full stream discharges the
    same delivered loan (the record alone implies nothing)."""

    reasons: List[str] = []
    _frac(principal)
    pays = [_frac(p) for p in payments]
    if any(p < 0 for p in pays):
        reasons.append("negative payment")

    booked = principal if delivered is True else Fraction(0)
    balance = booked
    for p in pays:                       # walk the stream by hand
        balance = balance - p
        if balance < 0:
            balance = Fraction(0)
    paid = sum(pays, Fraction(0))

    if claimed.get("booked") != booked:
        reasons.append("booked amount differs from independent derivation")
    if claimed.get("balance_after") != balance:
        reasons.append("end balance differs from independent derivation")
    if claimed.get("paid") != paid:
        reasons.append("paid total differs")
    if claimed.get("discharged") != (balance == 0):
        reasons.append("discharge verdict differs")
    if claimed.get("discharged_iff_covered") != ((balance == 0) == (booked <= paid)):
        reasons.append("discharged-iff-covered equivalence differs")
    if claimed.get("undelivered_balance_zero") is not True:
        reasons.append("undelivered ledger must have zero balance")
    if claimed.get("record_alone_implies_unpaid") is not False:
        reasons.append("a lending record alone must not imply non-discharge")
    if claimed.get("full_stream_discharges") is not True:
        reasons.append("a full repayment stream must discharge the loan")
    return CheckReport(not reasons, reasons)


