# D048 — admission-order rows by index-walking allocation
# ---------------------------------------------------------------------------

def _rows_by_index(amounts: List[Fraction],
                   payments: Sequence[Fraction]) -> List[List[Fraction]]:
    """Independent allocation: for each payment, walk the amounts by
    index with an explicit cash variable (no recursion, no v2
    waterfall, no zip)."""

    remaining = [Fraction(a) for a in amounts]
    rows: List[List[Fraction]] = []
    for p in payments:
        cash = Fraction(p)
        row: List[Fraction] = []
        for i in range(len(remaining)):
            take = remaining[i] if cash > remaining[i] else cash
            row.append(Fraction(take))
            cash = cash - take
            remaining[i] = remaining[i] - take
        rows.append(row)
    return rows


def check_D048(kinds: Sequence[str], amounts: Sequence[Fraction],
               idents: Sequence[int],
               payments: Sequence[Fraction],
               claimed_rows: Sequence[Sequence[Fraction]],
               claimed_balance: Fraction,
               claimed_idents: Sequence[int]) -> CheckReport:
    """Check a claimed offset run: rows must equal the index-walking
    derivation, every allocation nonnegative, every row within its
    payment, identities preserved, and the end balance must be
    max(due − paid, 0)."""

    reasons: List[str] = []
    amts = [_frac(a) for a in amounts]
    if any(a < 0 for a in amts):
        reasons.append("negative debt amount")
    pays = [_frac(p) for p in payments]
    if any(p < 0 for p in pays):
        reasons.append("negative payment")

    rows = _rows_by_index(amts, pays)
    if [list(r) for r in claimed_rows] != rows:
        reasons.append("rows differ from independent derivation")
    for p, row in zip(pays, rows):
        if any(a < 0 for a in row):
            reasons.append("negative allocation")
        if sum(row, Fraction(0)) > p:
            reasons.append("row exceeds its payment")
    if list(claimed_idents) != list(idents):
        reasons.append("debt identities not preserved")

    due = sum(amts, Fraction(0))
    end = due - sum(pays, Fraction(0))
    if end < 0:
        end = Fraction(0)
    if claimed_balance != end:
        reasons.append("end balance differs from max(due-paid, 0)")
    return CheckReport(not reasons, reasons)


def check_D048_stream_gates(claimed: dict) -> CheckReport:
    """The payment-id gate: a duplicated id (7 twice) must be reported
    illegal and distinct ids legal."""

    reasons: List[str] = []
    ids = [7, 7]
    duplicate_illegal = not (len(ids) == len(set(ids)))
    if claimed.get("duplicate_id_rejected") is not duplicate_illegal:
        reasons.append("duplicate-id gate differs")
    ids2 = [1, 2]
    distinct_legal = (len(ids2) == len(set(ids2)))
    if claimed.get("distinct_ids_legal") is not distinct_legal:
        reasons.append("distinct-id legality differs")
    return CheckReport(not reasons, reasons)


def check_D048_double_full(claimed: dict) -> CheckReport:
    """The double-full rejection: the legal row of a 150 payment on the
    interest-100/principal-200 ledger is [100, 50]; the double-full row
    [100, 200] exceeds the payment and never equals the real row."""

    reasons: List[str] = []
    legal_row = _rows_by_index([Fraction(100), Fraction(200)],
                               [Fraction(150)])[0]
    if legal_row != [Fraction(100), Fraction(50)]:
        reasons.append("independent legal row is [100, 50]")
    if claimed.get("real_allocs") != legal_row:
        reasons.append("real allocation differs from independent derivation")
    if claimed.get("double_full_row") != [Fraction(100), Fraction(200)]:
        reasons.append("the double-full row is [100, 200]")
    if claimed.get("double_full_exceeds_payment") is not True:
        reasons.append("the double-full row must exceed the payment")
    if claimed.get("never_equals_real") is not (
            legal_row != [Fraction(100), Fraction(200)]):
        reasons.append("double-full row must never equal the real row")
    return CheckReport(not reasons, reasons)


def check_D048_demo(claimed: dict) -> CheckReport:
    """The admission-order witness: (10, 100, 200) with a 150 payment
    offsets (10, 100, 40) leaving 160; a 350 payment clears everything."""

    reasons: List[str] = []
    part = _rows_by_index([Fraction(10), Fraction(100), Fraction(200)],
                          [Fraction(150)])[0]
    full = _rows_by_index([Fraction(10), Fraction(100), Fraction(200)],
                          [Fraction(350)])[0]
    if claimed.get("part_allocs") != part or part != [Fraction(10),
                                                      Fraction(100),
                                                      Fraction(40)]:
        reasons.append("partial allocation differs from (10,100,40)")
    if claimed.get("part_balance") != Fraction(160):
        reasons.append("partial balance differs from 160")
    if claimed.get("full_allocs") != full:
        reasons.append("full allocation differs")
    if claimed.get("full_balance") != Fraction(0):
        reasons.append("full payment must clear the ledger")
    return CheckReport(not reasons, reasons)


# ---------------------------------------------------------------------------
# D049 — charge components by direct division; cap by comparison
# ---------------------------------------------------------------------------

def _seg_by_division(base: Fraction, rate: Fraction, days: int,
                     denom: int) -> Fraction:
    """Independent component computation: (base × rate × days) / denom
    by Fraction division — a different expression than the reference's
    ratio multiplication."""

    return (Fraction(base) * Fraction(rate) * days) / denom


def check_D049(principal: Fraction, denom: int,
               term_rate: Fraction, term_days: int,
               overdue_rate: Fraction, overdue_days: int,
               penalty_rate: Fraction, penalty_days: int,
               cap: Fraction, claimed: dict) -> CheckReport:
    """Check the three components, their independence, the split
    additivity and the policy cap."""

    reasons: List[str] = []
    p = Fraction(principal)
    term = _seg_by_division(p, Fraction(term_rate), term_days, denom)
    over = _seg_by_division(p, Fraction(overdue_rate), overdue_days, denom)
    pen = _seg_by_division(p, Fraction(penalty_rate), penalty_days, denom)
    total = term + over + pen

    if claimed.get("term") != term:
        reasons.append("term component differs")
    if claimed.get("overdue") != over:
        reasons.append("overdue component differs")
    if claimed.get("penalty") != pen:
        reasons.append("penalty component differs")
    if claimed.get("total") != total:
        reasons.append("total differs from the component sum")
    if claimed.get("components_sum") is not True:
        reasons.append("components must sum to the total")

    # independence: term does not move when the overdue parameters move
    term2 = _seg_by_division(p, Fraction(term_rate), term_days, denom)
    _ = _seg_by_division(p, Fraction(overdue_rate) * 2, overdue_days + 30,
                         denom)
    if claimed.get("term_independent_of_overdue") is not (term2 == term):
        reasons.append("term component must be independent of overdue")

    # split additivity: d = d1 + d2 (cross-multiplied identity)
    d = term_days
    d1 = d // 2
    d2 = d - d1
    lhs = _seg_by_division(p, Fraction(term_rate), d, denom)
    rhs = (_seg_by_division(p, Fraction(term_rate), d1, denom)
           + _seg_by_division(p, Fraction(term_rate), d2, denom))
    if claimed.get("seg_split_sums") is not (lhs == rhs):
        reasons.append("segment split must be additive")

    if claimed.get("within_cap") is not (total <= Fraction(cap)):
        reasons.append("cap verdict differs")
    if claimed.get("cap") != Fraction(cap):
        reasons.append("cap value differs")
    return CheckReport(not reasons, reasons)


def check_D049_stacking(claimed: dict) -> CheckReport:
    """The stacking witness: 10+10+10 = 30 over the cap 24 rejected;
    10+10+0 = 20 within the cap."""

    reasons: List[str] = []
    all_total = sum((_seg_by_division(Fraction(100), Fraction(1, 10), 1, 1)
                     for _ in range(3)), Fraction(0))
    no_pen = all_total - _seg_by_division(Fraction(100), Fraction(1, 10),
                                          1, 1)
    if claimed.get("all_total") != all_total or all_total != Fraction(30):
        reasons.append("stacked total differs from 30")
    if claimed.get("all_within_24") is not (all_total <= Fraction(24)):
        reasons.append("30 must exceed the cap 24")
    if claimed.get("no_penalty_total") != no_pen:
        reasons.append("no-penalty total differs")
    if claimed.get("no_penalty_within_24") is not (no_pen <= Fraction(24)):
        reasons.append("20 must be within the cap 24")
    return CheckReport(not reasons, reasons)


