def check_D053(in_marriage: bool, spouse_signed: bool,
               common_intent: bool, household_use: bool,
               claimed: dict) -> CheckReport:
    """Independent joint-debt derivation by integer boolean arithmetic;
    the marriage period never enters the formula; the marriage-only
    configuration stays non-joint."""

    reasons: List[str] = []
    joint = bool(int(spouse_signed) |
                 (int(common_intent) & int(household_use)))
    if claimed.get("joint") is not joint:
        reasons.append("joint verdict differs")
    if claimed.get("marriage_flip_invariant") is not True:
        reasons.append("flipping the marriage period must not change it")
    if claimed.get("married_alone_not_joint") is not True:
        reasons.append("married-alone must stay non-joint")
    if claimed.get("signature_suffices") is not True:
        reasons.append("the spouse signature must suffice")
    if claimed.get("intent_use_suffice") is not True:
        reasons.append("intent+use must suffice")
    # the marriage-period field is truly inert in this derivation
    if claimed.get("in_marriage") is not in_marriage:
        reasons.append("marriage-period field differs")
    return CheckReport(not reasons, reasons)


