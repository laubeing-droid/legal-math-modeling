# D056 — fee consistency by forbidden-pair test; partition by two sums
# ---------------------------------------------------------------------------

def check_D056(rows: Sequence[Tuple[int, str, str, int, str, Fraction]],
               claimed: dict, beneficiary: int = 2) -> CheckReport:
    """Independent fee-ledger derivation: a row is consistent unless it
    is exactly the forbidden pair (supported, selfQuoted); the three
    fee kinds are pairwise distinct; the beneficiary grouping conserves
    the total (two accumulators in one pass)."""

    reasons: List[str] = []
    kinds = ("attorneyFee", "courtFee", "preservationFee")
    if len(set(kinds)) != 3 or "attorneyFee" == "principal":
        reasons.append("fee kinds must be pairwise distinct")
    if claimed.get("fee_kinds_distinct") is not True:
        reasons.append("distinctness flag differs")

    rows_ok = True
    for (ident, kind, basis, benef, status, amount) in rows:
        _frac(amount)
        if status == "supported" and basis == "selfQuoted":
            rows_ok = False
    if claimed.get("rows_consistent") is not rows_ok:
        reasons.append("row-consistency flag differs")
    if claimed.get("self_quoted_supported") is not False:
        reasons.append("a self-quoted row must never be auto-supported")
    if claimed.get("stipulated_supported") is not True:
        reasons.append("a contract-stipulated row can be supported")

    # two-accumulator partition in one pass
    own = Fraction(0)
    other = Fraction(0)
    for (_i, _k, _b, benef, _s, amount) in rows:
        if benef == beneficiary:
            own += Fraction(amount)
        else:
            other += Fraction(amount)
    total = own + other
    if claimed.get("beneficiary_total") != own:
        reasons.append("beneficiary grouping differs")
    if claimed.get("others_total") != other:
        reasons.append("complement grouping differs")
    if claimed.get("partition_conserved") is not (own + other == total):
        reasons.append("grouping must conserve the total")
    return CheckReport(not reasons, reasons)
