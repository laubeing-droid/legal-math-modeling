# D052 — responsible subject by branch table; beneficiary preservation
# ---------------------------------------------------------------------------

def check_D052(signer: int, capacity: str, principal, items, claimed: dict,
               payment: Fraction = Fraction(0)) -> CheckReport:
    """Independent responsible-subject derivation: pick from the
    (signer, principal) branch table; verify the signer is not the
    responsible subject when signing on behalf, and that the
    beneficiary sequence (``items`` are (ident, beneficiary) pairs)
    survives the payment unchanged."""

    reasons: List[str] = []
    if capacity == "onBehalfOf":
        resp = int(principal)
    elif capacity == "ownName":
        resp = int(signer)
    else:
        raise ValueError(f"unknown capacity: {capacity}")
    if claimed.get("responsible") != resp:
        reasons.append("responsible subject differs")
    if claimed.get("signer") != signer or \
            claimed.get("capacity") != capacity:
        reasons.append("encoding fields differ")
    if capacity == "onBehalfOf" and claimed.get(
            "signer_bears_all") is not False:
        reasons.append("the natural-person signer must not bear it all")
    before = claimed.get("beneficiaries_before")
    after = claimed.get("beneficiaries_after")
    if before != after or before != [it[1] for it in items]:
        reasons.append("beneficiary sequence differs from the input")
    if claimed.get("beneficiaries_preserved") is not True:
        reasons.append("beneficiary fields must be preserved")
    return CheckReport(not reasons, reasons)


