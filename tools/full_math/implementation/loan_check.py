# D051 — corporate-surety predicates by counting
# ---------------------------------------------------------------------------

def check_D051(events: Sequence[str], claimed: dict) -> CheckReport:
    """Independent corporate-guarantee derivation by occurrence
    counting: resolution ∧ signature establishes; either alone does
    not; on signature-only events the natural-person suretyship IS
    established — no blanket invalidation."""

    reasons: List[str] = []
    evs = list(events)
    res = sum(1 for e in evs if e == "boardResolution")
    sig = sum(1 for e in evs if e == "signed")
    corp = (res >= 1) and (sig >= 1)
    if claimed.get("corp_established") is not corp:
        reasons.append("corporate verdict differs")
    if claimed.get("resolution_present") is not (res >= 1):
        reasons.append("resolution presence differs")
    if claimed.get("signature_present") is not (sig >= 1):
        reasons.append("signature presence differs")
    if claimed.get("needs_both") is not True:
        reasons.append("resolution+signature must establish")
    if claimed.get("resolution_alone_insufficient") is not True:
        reasons.append("resolution alone must not establish")
    if claimed.get("same_events_corp_not_established") is not True:
        reasons.append("signature-only must leave the corp guarantee out")
    if claimed.get("same_events_natural_surety_established") is not True:
        reasons.append("signature-only must establish the natural surety")
    if claimed.get("no_blanket_invalidation") is not True:
        reasons.append("no blanket invalidation rule")
    return CheckReport(not reasons, reasons)


