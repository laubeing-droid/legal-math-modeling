# D054 — veil evaluation by match counting
# ---------------------------------------------------------------------------

def check_D054(edges: Sequence[str], claimed: dict) -> CheckReport:
    """Independent veil derivation: the evaluation counts heavy-edge
    matches (≥1 reaches personality mixing); light edges alone reach
    neither the evaluation nor the consequence."""

    reasons: List[str] = []
    es = list(edges)
    heavy = sum(1 for e in es if e in ("commingledFunds", "underControl"))
    mix = heavy >= 1
    if claimed.get("mix") is not mix:
        reasons.append("personality-mix verdict differs")
    if claimed.get("joint_due") is not mix:
        reasons.append("joint-liability must ride the evaluation alone")
    if claimed.get("consequence_is_evaluation") is not True:
        reasons.append("consequence must equal the evaluation")
    if claimed.get("phone_only_no_mix") is not True:
        reasons.append("a shared phone alone must not reach the evaluation")
    if claimed.get("phone_address_no_liability") is not True:
        reasons.append("phone+address must not generate liability")
    if claimed.get("commingled_reaches_both") is not True:
        reasons.append("commingled funds must reach both")
    if claimed.get("control_reaches_both") is not True:
        reasons.append("one-way control must reach both")
    if claimed.get("light_only") is not all(
            e in ("sharedPhone", "sharedAddress") for e in es):
        reasons.append("light-edge classification differs")
    return CheckReport(not reasons, reasons)


