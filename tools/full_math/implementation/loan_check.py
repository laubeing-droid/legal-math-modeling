# D050 — typed establishment events + priority walk
# ---------------------------------------------------------------------------

_REQ_EVENT_TABLE = (("suretyship", "signed"), ("mortgage", "registered"),
                    ("pledge", "delivered"))


def _required_by_scan(kind: str) -> str:
    """Independent required-event lookup by scanning the table (no
    dict)."""

    for k, ev in _REQ_EVENT_TABLE:
        if k == kind:
            return ev
    raise ValueError(f"unknown security kind: {kind}")


def _priority_walk(claims: Sequence[Fraction],
                   proceeds: Fraction) -> Tuple[List[Fraction], Fraction]:
    """Independent priority distribution: a cash bucket poured down the
    claims in order (min not used: explicit comparison)."""

    cash = Fraction(proceeds)
    out: List[Fraction] = []
    for c in claims:
        if cash > Fraction(c):
            out.append(Fraction(c))
            cash = cash - Fraction(c)
        else:
            out.append(Fraction(cash))
            cash = Fraction(0)
    return out, cash


def check_D050(events: Sequence[str],
               claims: Sequence[Fraction],
               proceeds: Fraction, claimed: dict) -> CheckReport:
    """Check the typed establishment verdicts and the priority
    waterfall with conservation and priority."""

    reasons: List[str] = []
    evs = list(events)
    required = {k: _required_by_scan(k) for k in
                ("suretyship", "mortgage", "pledge")}
    if claimed.get("required_events") != required:
        reasons.append("required-event table differs")
    if len(set(required.values())) != 3:
        reasons.append("required events must be pairwise distinct")
    if claimed.get("required_events_distinct") is not True:
        reasons.append("distinctness flag differs")

    def _has(ev: str) -> bool:
        return any(e == ev for e in evs)          # scan, not `in`

    if claimed.get("established", {}).get("mortgage") is not \
            _has(required["mortgage"]):
        reasons.append("mortgage establishment differs")
    if claimed.get("established", {}).get("pledge") is not \
            _has(required["pledge"]):
        reasons.append("pledge establishment differs")
    # the counterexample: signing alone establishes neither mortgage
    # nor pledge, but does establish the suretyship
    if claimed.get("signing_only_establishes_mortgage") is not False:
        reasons.append("signing alone must not establish a mortgage")
    if claimed.get("signing_only_establishes_pledge") is not False:
        reasons.append("signing alone must not establish a pledge")
    if _has("registered") and claimed.get(
            "registered_mortgage_established") is not True:
        reasons.append("registered mortgage must be established")
    if _has("delivered") and claimed.get(
            "delivered_pledge_established") is not True:
        reasons.append("delivered pledge must be established when delivered")

    cls = [Fraction(c) for c in claims]
    proc = Fraction(proceeds)
    rows, leftover = _priority_walk(cls, proc)
    if claimed.get("priority_rows") != rows:
        reasons.append("priority rows differ from independent walk")
    if claimed.get("leftover") != leftover:
        reasons.append("leftover differs")
    if claimed.get("distribution_conserved") is not (
            sum(rows, Fraction(0)) + leftover == proc):
        reasons.append("distribution must conserve the proceeds")
    later_positive = len(rows) > 1 and rows[1] > 0
    earlier_full = rows[0] == cls[0] if cls else False
    if claimed.get("later_positive_implies_earlier_full") is not (
            (not later_positive) or earlier_full):
        reasons.append("a positive later rank requires full earlier cover")
    return CheckReport(not reasons, reasons)


