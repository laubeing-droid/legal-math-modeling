# D055 — sourced candidates by table scan; empty rule base
# ---------------------------------------------------------------------------

def check_D055(candidates: Sequence[Tuple[bool, int]],
               claimed: dict) -> CheckReport:
    """Independent admission derivation: only sourced rows are admitted
    (scan the candidate table by hand); the incomeLow→cashImpossible
    rule base is empty, so insufficiency reads out unproven — never a
    fabricated negative fact."""

    reasons: List[str] = []
    table = [(bool(s), int(i)) for s, i in candidates]
    # the admission table: (ident, sourced) -> admitted?
    expect = {(i, s): s for s, i in table}
    if claimed.get("admissions") != expect:
        reasons.append("admission table differs from independent derivation")
    unsourced_ok = all(not expect[(i, s)] for s, i in table if not s)
    sourced_ok = all(expect[(i, s)] for s, i in table if s)
    if claimed.get("unsourced_unproven") is not unsourced_ok:
        reasons.append("an unsourced candidate must stay unproven")
    if claimed.get("sourced_admitted") is not sourced_ok:
        reasons.append("a sourced candidate must be admitted")
    shared = {i for s, i in table
              if (i, True) in expect and (i, False) in expect}
    differ_ok = all(expect[(i, True)] is not expect[(i, False)]
                    for i in shared)
    if claimed.get("same_id_sourced_unsourced_differ") is not differ_ok:
        reasons.append("same-id sourced/unsourced verdicts must differ")
    if claimed.get("cash_rules") != []:
        reasons.append("the cash rule base must be empty")
    if claimed.get("no_income_low_to_impossible_rule") is not True:
        reasons.append("no rule from income-low to cash-impossible")
    if claimed.get("insufficiency_is_unproven_not_negative") is not unsourced_ok:
        reasons.append("insufficiency must be unproven, not negative")
    return CheckReport(not reasons, reasons)


