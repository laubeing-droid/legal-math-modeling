_REQUIRED = {"suretyship": "signed", "mortgage": "registered",
             "pledge": "delivered"}


def check_sec(kind: str, events: Sequence[str]) -> bool:
    return _REQUIRED.get(kind) in events


def check_corp_surety(events: Sequence[str]) -> bool:
    return "boardResolution" in events and "signed" in events


def check_proceeds(claims: Sequence[Fraction], proceeds: Fraction,
                   claimed: Sequence[Fraction]) -> CheckReport:
    """Independent priority distribution: walk the claims with a running
    remainder; verify conservation and the seniority property (a later
    positive recovery forces every senior claim fully satisfied)."""

    reasons: List[str] = []
    rem = _frac(proceeds)
    rows: List[Fraction] = []
    for c in claims:
        _frac(c)
        a = c if c <= rem else rem
        rows.append(a)
        rem -= a
    if list(claimed) != rows:
        reasons.append("distribution differs from independent derivation")
    if sum(rows, F(0)) + rem != proceeds:
        reasons.append("proceeds conservation broken")
    # constraint checks run on the CLAIMED list itself (a tampered list must
    # fail on its own merits, not only by differing from the derivation)
    for i, (c, a) in enumerate(zip(claims, claimed)):
        if a > c:
            reasons.append("recovery exceeds its claim")
        if a < c:
            for later in list(claimed)[i + 1:]:
                if later != 0:
                    reasons.append("seniority violation: junior positive "
                                   "while senior unsatisfied")
            break
    return CheckReport(not reasons, reasons)


# ---------------------------------------------------------------------------
# 5. Intervals: independent endpoint algebra
# ---------------------------------------------------------------------------

def check_inter(lo1, hi1, lo2, hi2, claimed) -> CheckReport:
    """Fail-closed intersection recomputed with explicit comparisons."""

    lo = lo1 if lo1 >= lo2 else lo2
    hi = hi1 if hi1 <= hi2 else hi2
    expect = None if lo > hi else (lo, hi)
    if claimed != expect:
        return CheckReport.fail(f"intersection {claimed} != {expect}")
    return CheckReport.pass_()


def check_scale(c, lo, hi, claimed) -> CheckReport:
    if c < 0:
        return CheckReport.fail("negative scale")
    if claimed != (c * lo, c * hi):
        return CheckReport.fail("scaled endpoints differ")
    return CheckReport.pass_()


def check_cause_times_loss(c_lo, c_hi, l_lo, l_hi, claimed) -> CheckReport:
    """Four-endpoint product recomputed longhand."""

    prods = [c_lo * l_lo, c_lo * l_hi, c_hi * l_lo, c_hi * l_hi]
    lo, hi = min(prods), max(prods)
    if claimed != (lo, hi):
        return CheckReport.fail("cause×loss endpoints differ")
    if not (0 <= lo <= hi):
        return CheckReport.fail("cause×loss not a share interval")
    return CheckReport.pass_()


def check_fault_ok(lo, hi) -> bool:
    return 0 <= lo and hi <= 1


def check_contained(a, b) -> bool:
    return b[0] <= a[0] and a[1] <= b[1]


# ---------------------------------------------------------------------------
# 6. Gates / shares / modes
# ---------------------------------------------------------------------------

def check_legal_shares(gates: Sequence[bool],
                       shares: Sequence[Fraction]) -> bool:
    if len(gates) != len(shares):
        return False
    total = F(0)
    for g, s in zip(gates, shares):
        _frac(s)
        if s < 0:
            return False
        if not g and s != 0:
            return False
        total += s
    if all(gates) and total != 1:
        return False
    return True


def check_external_due(mode: str, loss: Fraction, share: Fraction,
                       primary: Fraction, secondary: Fraction,
                       claimed: Fraction) -> bool:
    if mode == "several":
        expect = share
    elif mode == "joint":
        expect = loss
    elif mode == "supplementary":
        unpaid = loss - primary if loss > primary else F(0)
        expect = unpaid if unpaid < secondary else secondary
    else:
        return False
    return claimed == expect


def check_joint_recovery(loss: Fraction,
                         recoveries: Sequence[Fraction]) -> bool:
    return sum((_frac(r) for r in recoveries), F(0)) <= loss


def check_recourse_pool(paid: Sequence[Fraction],
                        shares: Sequence[Fraction]) -> bool:
    if sum(paid, F(0)) != sum(shares, F(0)):
        return False
    rec = defi = F(0)
    for p, s in zip(paid, shares):
        rec += (p - s) if p > s else F(0)
        defi += (s - p) if s > p else F(0)
    return rec == defi


def check_supp(primary: Fraction, secondary: Fraction, loss: Fraction,
               claimed: Tuple[Fraction, Fraction]) -> bool:
    first = primary if primary <= loss else loss
    rest = loss - first
    second = secondary if secondary <= rest else rest
    return claimed == (first, second)


# ---------------------------------------------------------------------------
# 7. Loss dedup
# ---------------------------------------------------------------------------

def check_dedup(entries: Sequence[Tuple[Tuple[int, int, int, int], Fraction]],
                claimed: Sequence[Tuple[Tuple[int, int, int, int], Fraction]]
                ) -> CheckReport:
    """Independent first-seen dedup via an ordered dict; also verifies the
    no-inflation property on nonnegative amounts."""

    reasons: List[str] = []
    seen = set()
    expect: List[Tuple[Tuple[int, int, int, int], Fraction]] = []
    for key, amt in entries:
        _frac(amt)
        if key not in seen:
            seen.add(key)
            expect.append((key, amt))
    if list(claimed) != expect:
        reasons.append("dedup result differs from independent derivation")
    orig_total = sum((a for _, a in entries), F(0))
    dedup_total = sum((a for _, a in claimed), F(0))
    if dedup_total > orig_total:
        reasons.append("dedup inflated the total")
    keys = [k for k, _ in claimed]
    if len(keys) != len(set(keys)):
        reasons.append("duplicate keys survived dedup")
    return CheckReport(not reasons, reasons)


# ---------------------------------------------------------------------------
# 8. Remedies / scenario witness
# ---------------------------------------------------------------------------

def check_monetary_blind_spot(remedies_a: Sequence,
                              remedies_b: Sequence) -> bool:
    """Both lists share the monetary total but differ as obligations —
    the money-only projection must not be treated as the whole remedy."""

    ta = sum((r for r in remedies_a if isinstance(r, Fraction)), F(0))
    tb = sum((r for r in remedies_b if isinstance(r, Fraction)), F(0))
    return ta == tb and list(remedies_a) != list(remedies_b)


def check_same_witness(scen_id: int, ratios, values, limit, witness) -> bool:
    return (scen_id == witness["scen_id"] and list(ratios) == list(witness["ratios"])
            and list(values) == list(witness["values"]))


# ---------------------------------------------------------------------------
# 9. Admission / tort partition / imputation
# ---------------------------------------------------------------------------

def check_admitted(cand: Tuple[bool, int]) -> bool:
    return cand[0]


def check_tort_partition(cands: Sequence[Tuple[str, bool]]):
    sel = [c for c in cands if c[1] is True]
    res = [c for c in cands if c[1] is False]
    return sel, res


def check_imputed(gate: bool, cause_lo: Fraction) -> bool:
    return gate is True and _frac(cause_lo) > 0
