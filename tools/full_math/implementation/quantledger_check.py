"""Independent checker for the unified quantity-ledger layer.

ZERO sharing discipline (stricter than the sibling checkers): this module
does NOT import ``quantledger_ref`` — not its functions and not its data
classes.  Every check re-derives the contract semantics inline from plain
tuples/dicts, using different code paths than the reference (while-loop
recursion instead of the v2 waterfall, direct telescoping arithmetic,
four-endpoint enumeration written out longhand).  The reference's outputs
are only ever compared against these independently derived expectations;
no witness callback and no expected value generated by the main
implementation is ever trusted.

Lean contract: JurisLean.Seams.UnifiedQuantLedger (W2-A B06/B07 substrate,
same-source with W2-B N01/N02).
"""
from __future__ import annotations

from fractions import Fraction
from typing import Dict, List, Optional, Sequence, Tuple

F = Fraction


class CheckReport:
    __slots__ = ("ok", "reasons")

    def __init__(self, ok: bool, reasons: Sequence[str] = ()) -> None:
        self.ok = bool(ok)
        self.reasons = tuple(reasons)

    @classmethod
    def pass_(cls) -> "CheckReport":
        return cls(True)

    @classmethod
    def fail(cls, *reasons: str) -> "CheckReport":
        return cls(False, reasons)

    def __bool__(self) -> bool:
        return self.ok


def _frac(x) -> Fraction:
    if type(x) is not Fraction:
        raise TypeError(f"expected Fraction, got {type(x).__name__}")
    return x


# ---------------------------------------------------------------------------
# 2. Ledger: independent admission-order allocation by while-loop
# ---------------------------------------------------------------------------

def derive_rows(amounts: Sequence[Fraction],
                payments: Sequence[Fraction]) -> List[List[Fraction]]:
    """Independent re-derivation of the admission-order rows: for each
    payment walk the debt list with a running remainder, allocating
    min(remainder, debt) by hand."""

    cur = [_frac(a) for a in amounts]
    rows: List[List[Fraction]] = []
    for p in payments:
        _frac(p)
        rem = p
        row: List[Fraction] = []
        for i in range(len(cur)):
            a = min(rem, cur[i]) if rem < cur[i] else cur[i]
            row.append(a)
            rem -= a
            cur[i] = cur[i] - a
        rows.append(row)
    return rows


def check_ledger(amounts: Sequence[Fraction],
                 payments: Sequence[Fraction],
                 claimed_rows: Sequence[Sequence[Fraction]],
                 claimed_outstanding: Fraction) -> CheckReport:
    """Check a claimed ledger run: rows must equal the independent
    derivation, every allocation nonnegative, every row within its payment,
    and the end balance must be max(due − paid, 0)."""

    reasons: List[str] = []
    if any(_frac(a) < 0 for a in amounts):
        reasons.append("negative debt amount")
    if any(_frac(p) < 0 for p in payments):
        reasons.append("negative payment")
    rows = derive_rows(amounts, payments)
    if [list(r) for r in claimed_rows] != rows:
        reasons.append("rows differ from independent derivation")
    for p, row in zip(payments, rows):
        if any(a < 0 for a in row):
            reasons.append("negative allocation entry")
        if sum(row, F(0)) > p:
            reasons.append("row total exceeds its payment")
    due = sum(amounts, F(0))
    paid = sum(payments, F(0))
    expect = due - paid if due > paid else F(0)
    bal = sum((d - sum(col, F(0)) for d, col in zip(amounts, zip(*rows))),
              F(0)) if rows else due
    if bal != expect:
        reasons.append("columnwise balance is not max(due-paid, 0)")
    if _frac(claimed_outstanding) != expect:
        reasons.append("claimed outstanding is not max(due-paid, 0)")
    return CheckReport(not reasons, reasons)


def check_stream_legal(payments: Sequence[Tuple[int, Fraction]]) -> bool:
    seen = set()
    for pid, amt in payments:
        if pid in seen:
            return False
        seen.add(pid)
        _frac(amt)
        if amt < 0:
            return False
    return True


def check_status_consistent(kind: str, basis: str, status: str) -> bool:
    return status != "supported" or basis != "selfQuoted"


def check_beneficiary_partition(amounts: Sequence[Fraction],
                                beneficiaries: Sequence[int]) -> bool:
    total = sum(amounts, F(0))
    by = {}
    for a, b in zip(amounts, beneficiaries):
        by[b] = by.get(b, F(0)) + a
    return sum(by.values(), F(0)) == total


# ---------------------------------------------------------------------------
# 3. Charges: independent component arithmetic
# ---------------------------------------------------------------------------

def check_charges(principal: Fraction, denom: int, term_rate: Fraction,
                  term_days: int, overdue_rate: Fraction, overdue_days: int,
                  penalty_rate: Fraction, penalty_days: int, cap: Fraction,
                  claimed_total: Fraction) -> CheckReport:
    """Recompute the three components as (p × r × d) / D fractions by cross
    multiplication (a different normalization than the reference's F(d, D))."""

    reasons: List[str] = []
    comps = []
    for rate, days in ((term_rate, term_days), (overdue_rate, overdue_days),
                       (penalty_rate, penalty_days)):
        _frac(rate)
        if days < 0 or denom <= 0:
            reasons.append("bad segment parameters")
            comps.append(F(0))
            continue
        comps.append(principal * rate * Fraction(days) / Fraction(denom))
    total = sum(comps, F(0))
    if _frac(claimed_total) != total:
        reasons.append("component total differs")
    if total > cap:
        reasons.append("total exceeds policy cap")
    return CheckReport(not reasons, reasons)


def check_compound(b: Fraction, r: Fraction, d1: int, d2: int,
                   denom: int) -> bool:
    """Two-period compound equals simple parts + interest-on-interest."""

    inner = b * r * Fraction(d1) / Fraction(denom)
    compound = (b + inner) + (b + inner) * r * Fraction(d2) / Fraction(denom)
    parts = (b + inner) + b * r * Fraction(d2) / Fraction(denom) \
        + inner * r * Fraction(d2) / Fraction(denom)
    return compound == parts and compound >= parts - (parts - compound)


def check_seg_split(base: Fraction, rate: Fraction, days: int,
                    d1: int, denom: int) -> bool:
    """Splitting at d1 conserves the segment interest."""

    d2 = days - d1
    if d1 < 0 or d2 < 0:
        return False
    whole = base * rate * Fraction(days) / Fraction(denom)
    left = base * rate * Fraction(d1) / Fraction(denom)
    right = base * rate * Fraction(d2) / Fraction(denom)
    return left + right == whole


