# D063 — non-monetary remedies, by isinstance walk
# ---------------------------------------------------------------------------

def check_D063(remedies: Sequence, claimed: dict) -> CheckReport:
    """Independent remedy derivation: an amount view exists only for
    money (isinstance walk), the non-monetary trio carries None, and
    the two witness lists share the monetary total 100 while remaining
    different obligations."""

    reasons: List[str] = []
    rows = list(remedies)
    amounts = []
    for r in rows:
        if type(r) is Fraction:
            amounts.append(r)
        else:
            amounts.append(None)
    if claimed.get("amounts") != amounts:
        reasons.append("amount views differ from the isinstance walk")

    nonmonetary = ("restitution", "cessation", "apology")
    if claimed.get("nonmonetary_amounts_none") is not True:
        reasons.append("non-monetary remedies must carry no amount")
    if claimed.get("money_amounts_preserved") is not True:
        reasons.append("money amounts must be preserved exactly")

    def _total(xs) -> Fraction:
        acc = Fraction(0)
        for x in xs:
            if type(x) is Fraction:
                acc += x
        return acc

    if claimed.get("monetary_total") != _total(rows):
        reasons.append("monetary total differs from the independent walk")
    if claimed.get("witness_total_with_apology") != Fraction(100):
        reasons.append("the apology list's monetary total is 100")
    if claimed.get("witness_total_money_only") != Fraction(100):
        reasons.append("the money-only list's monetary total is 100")
    if claimed.get("witness_totals_equal") is not True:
        reasons.append("the two witness totals must be equal")
    if claimed.get("witness_lists_differ") is not True:
        reasons.append("the two witness lists must remain different")
    if claimed.get("apology_not_dropped") is not True:
        reasons.append("the apology must not vanish into a zero amount")
    return CheckReport(not reasons, reasons)


