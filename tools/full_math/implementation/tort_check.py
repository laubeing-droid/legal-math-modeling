# D059 — gate/share legality, by early-return loop
# ---------------------------------------------------------------------------

def _legal_by_loop(gates: Sequence[bool], shares: Sequence[Fraction]) -> bool:
    """Independent legality: single pass with early returns (no zip,
    no all())."""

    if len(gates) != len(shares):
        return False
    total = Fraction(0)
    every_open = True
    for i in range(len(gates)):
        s = shares[i]
        if type(s) is not Fraction or s < 0:
            return False
        if gates[i] is False and s != 0:
            return False
        if gates[i] is False:
            every_open = False
        total += s
    if every_open and total != 1:
        return False
    return True


def check_D059(gates: Sequence[bool], shares: Sequence[Fraction],
               claimed: dict) -> CheckReport:
    """Check the gate/share separation: the claimed legality equals the
    loop derivation, a closed gate forces zero, the masked (closed gate,
    1/10 share) configuration is illegal, and the open 1/4+3/4
    configuration is legal."""

    reasons: List[str] = []
    gs = [bool(g) for g in gates]
    ss = [_frac(s) for s in shares]
    legal = _legal_by_loop(gs, ss)
    if claimed.get("legal") is not legal:
        reasons.append("legality verdict differs from the loop derivation")

    closed_zero = True
    for i in range(len(gs)):
        if gs[i] is False and ss[i] != 0:
            closed_zero = False
    if claimed.get("closed_gate_zero_share") is not closed_zero:
        reasons.append("a closed gate must force a zero share")

    bad = _legal_by_loop([False, True], [Fraction(1, 10), Fraction(9, 10)])
    if bad:
        reasons.append("the masked closed-gate configuration must be illegal")
    if claimed.get("small_share_mask_illegal") is not (not bad):
        reasons.append("masked-configuration flag differs")

    good = _legal_by_loop([True, True], [Fraction(1, 4), Fraction(3, 4)])
    if not good:
        reasons.append("the open 1/4+3/4 configuration must be legal")
    if claimed.get("open_shares_legal") is not good:
        reasons.append("open-configuration flag differs")

    every_open = all(gs)
    total = Fraction(0)
    for s in ss:
        total += s
    if claimed.get("all_open_sum_one") is not ((not every_open) or total == 1):
        reasons.append("all-open shares must sum to one")
    return CheckReport(not reasons, reasons)


