# D058 — typed relations + layering, by four-product tables
# ---------------------------------------------------------------------------

def _four_products(a_lo, a_hi, b_lo, b_hi) -> Tuple[Fraction, Fraction]:
    """The four-endpoint product table reduced by explicit pairwise
    comparison (no min/max over iterables)."""

    ps = [a_lo * b_lo, a_lo * b_hi, a_hi * b_lo, a_hi * b_hi]
    lo = ps[0]
    for p in ps[1:]:
        if p < lo:
            lo = p
    hi = ps[0]
    for p in ps[1:]:
        if p > hi:
            hi = p
    return lo, hi


def check_D058(cause_lo: Fraction, cause_hi: Fraction,
               loss_lo: Fraction, loss_hi: Fraction,
               fault_lo: Fraction, fault_hi: Fraction,
               legal_gate: bool, claimed: dict) -> CheckReport:
    """Independent causation layering: three distinct tags with
    cross-tag operations rejected, the cause×loss product equals the
    four-endpoint table, the [0,1] fault well-formedness survives
    halving, and imputation needs gate AND positive lower bound — the
    [9/10, 1] measure with a closed gate never imputes."""

    reasons: List[str] = []
    for v in (cause_lo, cause_hi, loss_lo, loss_hi, fault_lo, fault_hi):
        _frac(v)
    tags = ("loss", "cause", "fault")
    if len(set(tags)) != 3:
        reasons.append("tags must be pairwise distinct")
    if claimed.get("tags_distinct") is not True:
        reasons.append("distinctness flag differs")
    if claimed.get("tag_kinds") != tags:
        reasons.append("tag kinds differ")
    if claimed.get("cross_tag_rejected") is not True:
        reasons.append("cross-tag interval operations must be rejected")

    lo, hi = _four_products(cause_lo, cause_hi, loss_lo, loss_hi)
    if claimed.get("product") != (lo, hi):
        reasons.append("cause×loss product differs from the four-endpoint table")
    x = (cause_lo + cause_hi) / 2
    y = (loss_lo + loss_hi) / 2
    inside = lo <= x * y <= hi
    if claimed.get("product_sound_interior") is not inside:
        reasons.append("an interior product must lie inside the product interval")

    fw = fault_lo >= 0 and fault_hi <= 1
    if claimed.get("fault_wellformed") is not fw:
        reasons.append("fault well-formedness differs")
    scaled_lo, scaled_hi = fault_lo / 2, fault_hi / 2
    fws = scaled_lo >= 0 and scaled_hi <= 1
    if claimed.get("fault_scaled_wellformed") is not fws:
        reasons.append("[0,1] scaling must preserve fault well-formedness")

    imput = legal_gate is True and cause_lo > 0
    if claimed.get("imputed") is not imput:
        reasons.append("imputation verdict differs")
    if claimed.get("imputed_iff_gate_and_positive_lo") is not True:
        reasons.append("imputation must equal gate ∧ positive lower bound")
    if claimed.get("strong_measure_gate_closed_not_imputed") is not True:
        reasons.append("a closed gate must block a [9/10,1] measure")
    return CheckReport(not reasons, reasons)


