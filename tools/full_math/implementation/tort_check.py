# D064 — same-witness summary, by field-by-field comparison
# ---------------------------------------------------------------------------

def check_D064(scen_id: int, ratios: Sequence[Fraction],
               values: Sequence[Fraction], record, claimed: dict) -> CheckReport:
    """Independent same-witness derivation: compare the record's three
    fields against the witness by hand, inherit the ratio conservation,
    and reject the mixed record against both single witnesses
    (``record`` is (scenId, ratios, values, limit))."""

    reasons: List[str] = []
    w_id = int(scen_id)
    w_ratios = tuple(_frac(r) for r in ratios)
    w_values = tuple(_frac(v) for v in values)
    r_id, r_ratios, r_values, _limit = record
    same = (int(r_id) == w_id and tuple(r_ratios) == w_ratios
            and tuple(r_values) == w_values)
    if claimed.get("from_same_witness") is not same:
        reasons.append("same-witness verdict differs from field comparison")
    if claimed.get("fields_from_witness") is not (
            int(r_id) == w_id and tuple(r_ratios) == w_ratios
            and tuple(r_values) == w_values):
        reasons.append("the record's fields must be the witness's projections")

    w_sum = Fraction(0)
    for r in w_ratios:
        w_sum += r
    r_sum = Fraction(0)
    for r in r_ratios:
        r_sum += r
    if claimed.get("witness_ratio_sum") != w_sum:
        reasons.append("witness ratio sum differs")
    if claimed.get("record_ratio_sum") != r_sum:
        reasons.append("record ratio sum differs")
    if claimed.get("ratio_conservation_inherited") is not (
            (not same) or (w_sum == 1 and r_sum == 1)):
        reasons.append("a same-witness record must inherit the conservation")

    wa = (1, (Fraction(1),), (Fraction(100),))
    wb = (2, (Fraction(1),), (Fraction(999),))
    mixed = (1, (Fraction(1),), (Fraction(999),), Fraction(0))
    mix_rejected = (
        not (mixed[0] == wa[0] and mixed[1] == wa[1] and mixed[2] == wa[2])
        and not (mixed[0] == wb[0] and mixed[1] == wb[1] and mixed[2] == wb[2]))
    if claimed.get("cross_scenario_mix_rejected") is not mix_rejected:
        reasons.append("the cross-scenario mix must match no single witness")
    return CheckReport(not reasons, reasons)
