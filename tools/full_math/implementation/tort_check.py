# D060 — external duties by branch table + recourse by conditionals
# ---------------------------------------------------------------------------

def _external_by_branch(mode: str, loss: Fraction, share: Fraction,
                        primary: Fraction, secondary: Fraction) -> Fraction:
    """Independent external duty: explicit branch table (no mode
    dispatch function)."""

    if mode == "several":
        return share
    if mode == "joint":
        return loss
    if mode == "supplementary":
        gap = loss - primary
        if gap < 0:
            gap = Fraction(0)
        return gap if gap < secondary else secondary
    raise ValueError(f"unknown mode: {mode}")


def check_D060(loss: Fraction, internal_share: Fraction,
               primary_due: Fraction, secondary_due: Fraction,
               recoveries: Sequence[Fraction],
               paid: Sequence[Fraction],
               internal_shares: Sequence[Fraction],
               claimed: dict) -> CheckReport:
    """Check the three external duties, the recovery constraint, the
    recourse/deficit pool and the supplementary order semantics."""

    reasons: List[str] = []
    L, S = _frac(loss), _frac(internal_share)
    P, D = _frac(primary_due), _frac(secondary_due)
    if claimed.get("several_due") != _external_by_branch("several", L, S, P, D):
        reasons.append("several duty differs from the branch table")
    if claimed.get("several_equals_share") is not (claimed.get("several_due") == S):
        reasons.append("several duty must equal the internal share")
    if claimed.get("joint_due") != _external_by_branch("joint", L, S, P, D):
        reasons.append("joint duty differs from the branch table")
    if claimed.get("joint_equals_loss") is not (claimed.get("joint_due") == L):
        reasons.append("joint duty must equal the full loss")

    supp = _external_by_branch("supplementary", L, S, P, D)
    if claimed.get("supp_due") != supp:
        reasons.append("supplementary duty differs from the branch table")
    gap = L - P
    if gap < 0:
        gap = Fraction(0)
    capped = gap if gap < D else D
    if claimed.get("supp_is_unpaid_remainder_capped") is not (supp == capped):
        reasons.append("supplementary duty must be the capped unpaid remainder")

    # supplementary waterfall by cash walk (loss poured onto primary)
    cash = L
    primary_gets = P if cash > P else cash
    cash = cash - primary_gets
    secondary_gets = D if cash > D else cash
    if claimed.get("supp_rows") != (primary_gets, secondary_gets):
        reasons.append("supplementary rows differ from the cash walk")
    if claimed.get("supp_zero_when_primary_covers") is not True:
        reasons.append("a covering primary must leave the supplement zero")

    rec_total = Fraction(0)
    for r in recoveries:
        rec_total += _frac(r)
    if claimed.get("recovery_total") != rec_total:
        reasons.append("recovery total differs")
    if claimed.get("recovery_ok") is not (rec_total <= L):
        reasons.append("recovery constraint differs")
    if claimed.get("double_full_violates") is not True:
        reasons.append("two full-100 recoveries must violate a 100 loss")

    pool_left = Fraction(0)
    pool_right = Fraction(0)
    for i in range(len(paid)):
        over = paid[i] - internal_shares[i]
        under = internal_shares[i] - paid[i]
        pool_left += over if over > 0 else Fraction(0)
        pool_right += under if under > 0 else Fraction(0)
    if claimed.get("recourse") != [
            max(paid[i] - internal_shares[i], Fraction(0))
            for i in range(len(paid))]:
        reasons.append("recourse rows differ")
    if claimed.get("deficit") != [
            max(internal_shares[i] - paid[i], Fraction(0))
            for i in range(len(paid))]:
        reasons.append("deficit rows differ")
    if claimed.get("recourse_pool_equals_deficit_pool") is not (
            pool_left == pool_right):
        reasons.append("the recourse pool must equal the deficit pool")
    return CheckReport(not reasons, reasons)


