# D062 — shared-base consistency by manual accumulators + endpoint tuples
# ---------------------------------------------------------------------------

def check_D062(base: Fraction, shares: Sequence[Fraction],
               recoveries: Sequence[Fraction],
               paid: Sequence[Fraction],
               internal_shares: Sequence[Fraction],
               claimed: dict) -> CheckReport:
    """Check the shared-base payment consistency: the share×base
    accumulator, the full-loss joint duty (never the reduced share), the
    recovery constraint in both directions, the balanced recourse pool
    and the interval endpoint algebra over plain (lo, hi) tuples."""

    reasons: List[str] = []
    B = _frac(base)
    ss = [_frac(s) for s in shares]
    total = Fraction(0)
    weighted = Fraction(0)
    for s in ss:
        total += s
        weighted += s * B
    if claimed.get("share_sum") != total:
        reasons.append("share sum differs")
    if claimed.get("sums_to_one") is not (total == 1):
        reasons.append("sums-to-one flag differs")
    if claimed.get("share_total_equals_base") is not (
            total == 1 and weighted == B):
        reasons.append("shares summing to one must pay exactly the base")

    quarter = Fraction(1, 4)
    if claimed.get("joint_due_full_loss") is not (B == _external_by_branch(
            "joint", B, quarter, Fraction(0), Fraction(0))):
        reasons.append("the joint duty must be the full loss")
    if claimed.get("joint_not_share_reduced") is not (B != quarter):
        reasons.append("the joint duty must never equal the reduced share")

    rec_total = Fraction(0)
    for r in recoveries:
        rec_total += _frac(r)
    if claimed.get("recovery_ok") is not (rec_total <= B):
        reasons.append("recovery constraint differs")
    if claimed.get("recovery_ok_iff_within_loss") is not True:
        reasons.append("the constraint must equal total ≤ loss")
    if claimed.get("single_full_recovery_ok") is not (
            Fraction(100) <= Fraction(100)):
        reasons.append("a single full recovery on the loss is legal")

    left = Fraction(0)
    right = Fraction(0)
    for i in range(len(paid)):
        over = paid[i] - internal_shares[i]
        under = internal_shares[i] - paid[i]
        left += over if over > 0 else Fraction(0)
        right += under if under > 0 else Fraction(0)
    if claimed.get("recourse_pool_equals_deficit_pool") is not (left == right):
        reasons.append("the recourse pool must equal the deficit pool")

    # endpoint algebra on plain tuples
    a = (Fraction(100), Fraction(200))
    b = (Fraction(150), Fraction(300))
    if claimed.get("interval_add_comm") is not (
            (a[0] + b[0], a[1] + b[1]) == (b[0] + a[0], b[1] + a[1])):
        reasons.append("interval addition must commute")
    ab = (a[0] + b[0], a[1] + b[1])
    band = (a[0] if a[0] > b[0] else b[0], a[1] if a[1] < b[1] else b[1])
    left_assoc = ((ab[0] + band[0], ab[1] + band[1]))
    right_assoc = ((a[0] + (b[0] + band[0]), a[1] + (b[1] + band[1])))
    if claimed.get("interval_add_assoc") is not (left_assoc == right_assoc):
        reasons.append("interval addition must associate")
    c = Fraction(1, 4)
    if claimed.get("interval_scale_distrib") is not (
            (c * (a[0] + b[0]), c * (a[1] + b[1]))
            == (c * a[0] + c * b[0], c * a[1] + c * b[1])):
        reasons.append("scaling must distribute over interval addition")
    if claimed.get("interval_scale_assoc") is not (
            (Fraction(1, 2) * (Fraction(1, 4) * a[0]),
             Fraction(1, 2) * (Fraction(1, 4) * a[1]))
            == (Fraction(1, 8) * a[0], Fraction(1, 8) * a[1])):
        reasons.append("interval scaling must associate")
    if claimed.get("common_base_band") != (Fraction(150), Fraction(200)):
        reasons.append("the common-base band must be [150, 200]")
    if claimed.get("common_base_band_is_150_200") is not True:
        reasons.append("common-base-band flag differs")
    if claimed.get("quarter_share_band") != (Fraction(25), Fraction(50)):
        reasons.append("the quarter of [100, 200] must be [25, 50]")
    return CheckReport(not reasons, reasons)


