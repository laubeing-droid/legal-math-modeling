# D061 — first-seen dedup by kept-key list scan
# ---------------------------------------------------------------------------

def check_D061(entries: Sequence[Tuple[int, int, int, int, Fraction]],
               claimed: dict) -> CheckReport:
    """Independent dedup: keep the first occurrence per key by scanning
    a kept-key list (no set), then verify the key freshness, the no-
    inflate bound, the identity on unique keys and the invoice/appraisal
    witness."""

    reasons: List[str] = []
    table = []
    for (ev, ben, item, t, amt) in entries:
        _frac(amt)
        table.append(((int(ev), int(ben), int(item), int(t)), Fraction(amt)))

    kept: List[Tuple[int, int, int, int]] = []
    dedup: List[Tuple[Tuple[int, int, int, int], Fraction]] = []
    for row in table:
        fresh = True
        for k in kept:
            if k == row[0]:
                fresh = False
        if fresh:
            kept.append(row[0])
            dedup.append(row)

    if claimed.get("keys_nodup_after") is not (len(set(kept)) == len(kept)):
        reasons.append("deduped keys must be duplicate-free")

    raw_sum = Fraction(0)
    for row in table:
        raw_sum += row[1]
    dedup_sum = Fraction(0)
    for row in dedup:
        dedup_sum += row[1]
    if claimed.get("raw_total") != raw_sum:
        reasons.append("raw total differs")
    if claimed.get("deduped_total") != dedup_sum:
        reasons.append("deduped total differs from the independent scan")
    if claimed.get("dedup_no_inflate") is not (dedup_sum <= raw_sum):
        reasons.append("dedup must never inflate a nonnegative ledger")
    if claimed.get("identity_when_nodup") is not (
            len(set(k for k, _ in table)) == len(table)
            and dedup == table):
        reasons.append("a unique-key ledger must dedup to itself")

    inv = ((1, 2, 3, 4), Fraction(1000))
    app = ((1, 2, 3, 4), Fraction(800))
    if claimed.get("witness_raw_total") != Fraction(1800):
        reasons.append("the raw invoice+appraisal total is 1800")
    if claimed.get("witness_deduped_total") != Fraction(1000):
        reasons.append("the deduped invoice+appraisal total is 1000")
    if claimed.get("witness_first_kept") is not True:
        reasons.append("the first occurrence (invoice) must be kept")
    if claimed.get("double_count_prevented") is not True:
        reasons.append("the same-key double count must be pressed back to 1000")
    return CheckReport(not reasons, reasons)


