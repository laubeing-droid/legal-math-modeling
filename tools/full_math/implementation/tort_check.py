# D057 — element selection + open residual, by index scan
# ---------------------------------------------------------------------------

def check_D057(cands: Sequence[Tuple[str, bool]], claimed: dict) -> CheckReport:
    """Independent classification: walk the candidate list by index
    twice (selected / residual), verify unmet candidates never appear in
    the selection and always appear in the residual, that the two
    buckets together cover every candidate exactly once, and that the
    unknown-scenario witness keeps a residual row (no claim-less
    output)."""

    reasons: List[str] = []
    table = [(str(k), bool(m)) for k, m in cands]
    selected: List[Tuple[str, bool]] = []
    residual: List[Tuple[str, bool]] = []
    for row in table:
        if row[1] is True:
            selected.append(row)
        else:
            residual.append(row)
    if claimed.get("selected") != selected:
        reasons.append("selected bucket differs from independent scan")
    if claimed.get("residual") != residual:
        reasons.append("residual bucket differs from independent scan")

    unmet_ok = True
    for row in table:
        if row[1] is False and row in selected:
            unmet_ok = False
    if claimed.get("unmet_never_selected") is not unmet_ok:
        reasons.append("an element-unmet candidate must never be selected")

    bucketed_ok = True
    for row in table:
        count = (1 if row in selected else 0) + (1 if row in residual else 0)
        if count != 1:
            bucketed_ok = False
    if claimed.get("every_candidate_bucketed") is not bucketed_ok:
        reasons.append("every candidate must land in exactly one bucket")
    if claimed.get("buckets_partition") is not (len(selected) + len(residual)
                                                == len(table)):
        reasons.append("bucket sizes must partition the candidate list")

    # the witness: unknown scenario + general tort — residual keeps one
    if claimed.get("witness_residual") != [("openResidual", False)]:
        reasons.append("the unknown scenario must stay in the residual")
    if claimed.get("witness_selected") != [("general", True)]:
        reasons.append("the general-tort candidate must be selected")
    if claimed.get("unknown_kept_in_residual") is not True:
        reasons.append("the unknown scenario must be kept in the residual")
    if claimed.get("unknown_still_claimable") is not (len(residual) >= 0):
        reasons.append("the residual must remain a claim carrier")
    if claimed.get("no_claimless_output") is not (len(selected) + len(residual)
                                                  == len(table)):
        reasons.append("a new scenario must not return a claim-less result")
    return CheckReport(not reasons, reasons)


