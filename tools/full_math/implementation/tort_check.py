"""Independent checker for the group-07 tort/damages entries.

ZERO sharing discipline (same as the B06 sibling): this module does NOT
import ``tort_ref`` — not its functions, not its data classes, and not
the shared ``quantledger_ref`` surface either.  Every check re-derives
the contract semantics inline from plain tuples, dicts and Fractions,
using different code paths than the reference (index scans instead of
comprehensions, explicit four-product tables instead of TagIv
arithmetic, early-return loops instead of all()/zip, endpoint tuples
instead of the IvQ class, manual accumulators instead of sum()).  The
reference's outputs are only ever compared against these independently
derived expectations; no witness callback and no expected value
generated by the main implementation is ever trusted.

Lean contract: JurisLean.FullMath.Contracts.demand_D057 … demand_D064
(W2-A batch B07), over the shared carrier
JurisLean.Seams.UnifiedQuantLedger.
"""
from __future__ import annotations

from fractions import Fraction
from typing import List, Optional, Sequence, Tuple

F = Fraction


class CheckReport:
    __slots__ = ("ok", "reasons")

    def __init__(self, ok: bool, reasons: Sequence[str] = ()) -> None:
        self.ok = bool(ok)
        self.reasons = tuple(reasons)

    @classmethod
    def pass_(cls) -> "CheckReport":
        return cls(True)

    @classmethod
    def fail(cls, *reasons: str) -> "CheckReport":
        return cls(False, reasons)

    def __bool__(self) -> bool:
        return self.ok


def _frac(x) -> Fraction:
    if type(x) is not Fraction:
        raise TypeError(f"expected Fraction, got {type(x).__name__}")
    return x


