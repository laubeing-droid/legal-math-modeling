# D117 — order legality by position table, infeasibility by round counter
# ---------------------------------------------------------------------------

def _positions(order: Sequence[str]) -> dict:
    pos: dict = {}
    idx = 0
    while idx < len(order):
        pos[order[idx]] = idx
        idx += 1
    return pos


def _before(order: Sequence[str], pre: str, name: str) -> bool:
    pos = _positions(order)
    if pre in pos and name in pos:
        return pos[pre] < pos[name]
    return False


def check_D117(tasks: Sequence[Tuple[str, str, bool]],
               claimed: dict) -> CheckReport:
    """Independent scheduler: build the order round by round (a round
    counter bounds the passes; a round with no runnable task means
    infeasible), verify the emitted order positions against the
    prerequisite table, and verify the cycle reports None while the
    acyclic chain closes."""

    reasons: List[str] = []
    todo = [tuple(t) for t in tasks]
    done: List[str] = []
    rounds = 0
    while len(done) < len(todo):
        if rounds > len(todo) + 1:
            done = None  # defensive bound, never reached with correct data
            break
        rounds += 1
        advanced = False
        for (name, prereq, permitted) in todo:
            if name in done:
                continue
            if not permitted:
                continue
            if prereq == "" or prereq in done:
                done.append(name)
                advanced = True
                break
        if not advanced:
            done = None
            break
    feasible = done is not None
    if claimed.get("feasible") is not feasible:
        reasons.append("feasibility verdict differs from the round counter")
    if feasible and claimed.get("order") != done:
        reasons.append("emitted order differs from the independent rounds")

    if feasible:
        legal = len(done) == len(todo)
        pos = _positions(done)
        for (name, prereq, permitted) in todo:
            if not permitted:
                legal = False
            if name not in pos:
                legal = False
            elif prereq != "" and (prereq not in pos
                                   or not pos[prereq] < pos[name]):
                legal = False
        if claimed.get("order_legal") is not legal:
            reasons.append("order legality differs from the position table")

    ship = [("board-approval", "", True),
            ("signature", "board-approval", True),
            ("closing", "signature", True)]
    ship_expect = ["board-approval", "signature", "closing"]
    ship_ok = (claimed.get("ship_order") == ship_expect
               and claimed.get("ship_feasible") is True)
    if not ship_ok:
        reasons.append("the acyclic chain must close in order")

    cyc = [("task-a", "task-b", True), ("task-b", "task-a", True)]
    if claimed.get("cycle_verdict") is not None:
        reasons.append("the dependency cycle must be reported infeasible")
    if claimed.get("cycle_infeasible_reported") is not True:
        reasons.append("cycle infeasibility must be reported")
    probes = [["task-a", "task-b"], ["task-b", "task-a"], [],
              ["task-a"], ["task-a", "x", "task-b"], ["task-b", "q"]]
    any_legal = False
    for order in probes:
        pos = _positions(order)
        ok = len(order) == len(cyc)
        for (name, prereq, permitted) in cyc:
            if not permitted or name not in pos:
                ok = False
            elif prereq != "" and (prereq not in pos
                                   or not pos[prereq] < pos[name]):
                ok = False
        if ok:
            any_legal = True
    if claimed.get("no_unconditional_checklist_for_cycle") is not (
            not any_legal):
        reasons.append("no order may legally execute the cycle")
    return CheckReport(not reasons, reasons)


