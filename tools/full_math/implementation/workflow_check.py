"""Independent checker for the group-13 workflow-strategy entries.

ZERO sharing discipline (same as the B07 sibling): this module does NOT
import ``workflow_ref`` — not its functions, not its constants, not any
helper.  Every check re-derives the contract semantics inline from
plain tuples, dicts, ints and Fractions, using different code paths
than the reference (membership by index scan instead of list
comprehensions, schedule construction by explicit round counters
instead of while/restart, value tables by branch tables instead of
dict lookups, readouts by a three-arm branch instead of string
formatting, provenance by manual flag accumulation instead of
all()/any()).  The reference's outputs are only ever compared against
these independently derived expectations; no witness callback and no
expected value generated by the main implementation is ever trusted.

Lean contract: JurisLean.FullMath.Contracts.demand_D116 … demand_D123
(W2-A batch B13), first conjunct the registered Bellman component
JurisLean.FullMath.Numeric.bellman_onesided.
"""
from __future__ import annotations

from fractions import Fraction
from typing import List, Sequence, Tuple

F = Fraction


class CheckReport:
    __slots__ = ("ok", "reasons")

    def __init__(self, ok: bool, reasons: Sequence[str] = ()) -> None:
        self.ok = bool(ok)
        self.reasons = tuple(reasons)

    @classmethod
    def pass_(cls) -> "CheckReport":
        return cls(True)

    @classmethod
    def fail(cls, *reasons: str) -> "CheckReport":
        return cls(False, reasons)

    def __bool__(self) -> bool:
        return self.ok


def _frac(x) -> Fraction:
    if type(x) is not Fraction:
        raise TypeError(f"expected Fraction, got {type(x).__name__}")
    return x


