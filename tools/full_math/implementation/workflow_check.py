# D119 — ranking by selection maxima instead of insertion sort
# ---------------------------------------------------------------------------

def check_D119(items: Sequence[Tuple[str, int, int, bool]],
               claimed: dict) -> CheckReport:
    """Independent ranking: repeatedly select the maximum-score unblocked
    item (selection instead of insertion), verify descending readouts,
    the hard-block exclusion over the union of blocked names, the origin
    label, and the two weight-vector orders."""

    reasons: List[str] = []

    def score(it):
        return int(it[1]) * int(it[2])

    def rank_selection(pool):
        out: List[Tuple[str, int]] = []
        rest = [tuple(p) for p in pool]
        while rest:
            best_i = 0
            n = 1
            while n < len(rest):
                if score(rest[n]) > score(rest[best_i]):
                    best_i = n
                n += 1
            out.append((rest[best_i][0], score(rest[best_i])))
            rest.pop(best_i)
        return out

    unblocked = [tuple(i) for i in items if not i[3]]
    expect = rank_selection(unblocked)
    if claimed.get("readout") != expect:
        reasons.append("ranked readout differs from max-selection ranking")
    desc = True
    q = 1
    while q < len(expect):
        if expect[q - 1][1] < expect[q][1]:
            desc = False
        q += 1
    if claimed.get("sorted_descending") is not desc:
        reasons.append("readout scores must be non-increasing")

    blocked_names: List[str] = []
    for i in items:
        if i[3] and i[0] not in blocked_names:
            blocked_names.append(i[0])
    work_names = [e[0] for e in expect]
    excluded = True
    for bn in blocked_names:
        if bn in work_names:
            excluded = False
    if claimed.get("blocked_excluded_any_weight") is not excluded:
        reasons.append("hard-blocked items must never enter the work list")

    if claimed.get("origin") != "explicit-preference":
        reasons.append("the origin label must be the explicit preference")
    if claimed.get("origin_not_statutory") is not True:
        reasons.append("the origin label must not claim a statutory order")

    infra = [("power-grid", 4, 10, False), ("revenue-stream", 5, 3, False),
             ("ip-license", 1, 2, False)]
    if claimed.get("witness_readout") != rank_selection(infra):
        reasons.append("the 40/15/2 witness readout differs")
    blocked_top = [("unpermitted-plant", 10, 10, True),
                   ("power-grid", 4, 10, False),
                   ("revenue-stream", 5, 3, False)]
    if claimed.get("witness_blocked_not_in_worklist") is not (
            "unpermitted-plant" not in [e[0] for e in
                                        rank_selection(
                                            [i for i in blocked_top
                                             if not i[3]])]):
        reasons.append("the score-100 blocked plant must stay out")
    cfga = [("power-grid", 1, 2, False), ("revenue-stream", 3, 3, False)]
    cfgb = [("power-grid", 5, 2, False), ("revenue-stream", 1, 3, False)]
    if claimed.get("cfg_a_names") != [e[0] for e in rank_selection(cfga)]:
        reasons.append("weight config A order differs")
    if claimed.get("cfg_b_names") != [e[0] for e in rank_selection(cfgb)]:
        reasons.append("weight config B order differs")
    if claimed.get("weights_change_order") is not (
            [e[0] for e in rank_selection(cfga)]
            != [e[0] for e in rank_selection(cfgb)]):
        reasons.append("the two weight vectors must rank differently")
    return CheckReport(not reasons, reasons)


