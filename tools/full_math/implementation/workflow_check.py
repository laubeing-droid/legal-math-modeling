# D118 — legality by branch table, values by cross-multiplied integers
# ---------------------------------------------------------------------------

def check_D118(actions: Sequence[Tuple[str, str, bool, Fraction, Fraction,
                                      Fraction]],
               claimed: dict) -> CheckReport:
    """Independent legality: a branch table over the three kinds instead
    of pattern dispatch; values by Fraction cross-arithmetic computed
    fresh; the mandatory waiver witness and both value witnesses are
    re-derived; the Bellman one-sided bound is re-checked on a fresh
    two-state table with explicit accumulators."""

    reasons: List[str] = []
    table = [(("writtenConfirm"), True), (("waiver"), None),
             (("supplement"), True)]  # None = depends on waivable

    def legal_branch(kind, waivable):
        row = None
        for (k, v) in table:
            if k == kind:
                row = v
        if row is None:
            return waivable
        return row

    for a in actions:
        expect = legal_branch(a[0], a[2])
        got = None
        for row in claimed.get("legality", []):
            if row[0] == tuple(a):
                got = row[1]
        if got is not expect:
            reasons.append(f"legality of {a[0]} on waivable={a[2]}")
    if claimed.get("confirm_always_legal") is not (
            legal_branch("writtenConfirm", False)
            and legal_branch("writtenConfirm", True)):
        reasons.append("written confirmation must always be legal")
    if claimed.get("supplement_always_legal") is not (
            legal_branch("supplement", False)
            and legal_branch("supplement", True)):
        reasons.append("supplementary evidence must always be legal")
    if claimed.get("waiver_needs_waivable") is not (
            legal_branch("waiver", True)
            and not legal_branch("waiver", False)):
        reasons.append("a waiver is legal only on a waivable norm")
    if claimed.get("mandatory_waiver_illegal") is not True:
        reasons.append("the mandatory-norm waiver must stay illegal")

    def value_branch(prob, gain, cost):
        return _frac(prob) * _frac(gain) - _frac(cost)

    if claimed.get("witness_value_confirm") != value_branch(F(3, 4),
                                                            F(100), F(10)):
        reasons.append("confirm value must be 3/4*100-10 = 65")
    if claimed.get("witness_value_supplement") != value_branch(F(1, 2),
                                                               F(40), F(5)):
        reasons.append("supplement value must be 1/2*40-5 = 15")

    # fresh Bellman one-sided check with manual accumulators
    # states: clarify/closing; actions per state; rewards by table
    rewards = {("clarify", "seek-confirmation"): F(65),
               ("clarify", "proceed-anyway"): F(0),
               ("closing", "close"): F(100)}
    kernels = {("clarify", "seek-confirmation"): [("closing", F(3, 4)),
                                                  ("clarify", F(1, 4))],
               ("clarify", "proceed-anyway"): [("closing", F(1))],
               ("closing", "close"): [("closing", F(1))]}
    legal_by_state = {"clarify": ["seek-confirmation",
                                  "proceed-anyway"],
                      "closing": ["close"]}

    def q_of(s, a, v):
        acc = F(0)
        for (sp, prob) in kernels[(s, a)]:
            acc += prob * v[sp]
        return rewards[(s, a)] + F(9, 10) * acc

    def best_of(s, v):
        acts = legal_by_state[s]
        best = None
        for a in acts:
            q = q_of(s, a, v)
            if best is None or q > best:
                best = q
        return best

    v0 = {"clarify": F(0), "closing": F(0)}
    v1 = {s: best_of(s, v0) for s in ("clarify", "closing")}
    v2 = {s: best_of(s, v1) for s in ("clarify", "closing")}
    v3 = {s: best_of(s, v2) for s in ("clarify", "closing")}
    big_m = F(1, 10)
    y3 = {s: v3[s] + big_m for s in v3}
    bound = True
    for s in ("clarify", "closing"):
        if abs(v3[s] - y3[s]) > big_m:
            bound = False
        if best_of(s, v3) > best_of(s, y3) + F(9, 10) * big_m:
            bound = False
    if claimed.get("bellman_one_sided_bound_holds") is not bound:
        reasons.append("the one-sided Bellman bound must hold on the"
                       " fresh two-state table")
    horizons = claimed.get("bellman_horizons", {})
    h3 = horizons.get(3, horizons.get("3", {}))
    if _frac(h3.get("clarify", F(-1))) != v3["clarify"] \
            or _frac(h3.get("closing", F(-1))) != v3["closing"]:
        reasons.append("backward-induction horizon-3 values differ from"
                       " the fresh accumulation")
    return CheckReport(not reasons, reasons)


