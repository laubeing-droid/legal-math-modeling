# D121 — options by nested gate ladder
# ---------------------------------------------------------------------------

def check_D121(is_non_party: bool, stage_pre_trial: bool,
               filed_in_time: bool, claimed: dict) -> CheckReport:
    """Independent option set: a nested gate ladder (no table), the
    timeliness precondition by exhaustive context sweep, and the three
    witness contexts (full / party / late) re-derived."""

    reasons: List[str] = []

    def ladder(measure):
        if measure == "quash":
            if filed_in_time:
                return is_non_party
            return False
        if measure == "vacate":
            return filed_in_time
        if measure == "protective":
            if filed_in_time:
                return stage_pre_trial
            return False
        raise ValueError(measure)

    expect = []
    for m in ("quash", "vacate", "protective"):
        if ladder(m):
            expect.append(m)
    if claimed.get("options") != expect:
        reasons.append("option set differs from the gate ladder")

    def options_of(party, pre, timely):
        out = []
        if timely and party:
            out.append("quash")
        if timely:
            out.append("vacate")
        if timely and pre:
            out.append("protective")
        return out

    # timeliness precondition: with filed_in_time forced False every
    # gate in the ladder is False regardless of standing or stage
    timely_always = True
    for party in (True, False):
        for pre in (True, False):
            if options_of(party, pre, False) != []:
                timely_always = False
    if claimed.get("timeliness_precondition") is not timely_always:
        reasons.append("timeliness must gate every measure")

    if claimed.get("full_context_options") != options_of(True, True, True):
        reasons.append("the full context must yield all three options")
    if claimed.get("party_context_options") != options_of(False, True, True):
        reasons.append("the party context must miss quash")
    if claimed.get("party_misses_quash") is not True:
        reasons.append("the party context must not get the quash path")
    if claimed.get("nonparty_path_not_unconditional") is not (
            options_of(False, True, True) != options_of(True, True, True)):
        reasons.append("the non-party path is not unconditional")
    if claimed.get("late_context_empty") is not (
            options_of(True, True, False) == []):
        reasons.append("the late context must be empty")
    if claimed.get("deadline_not_cured") is not True:
        reasons.append("the deadline is not cured by standing or stage")
    return CheckReport(not reasons, reasons)


