# D122 — coverage by row-matching scans
# ---------------------------------------------------------------------------

def check_D122(claimed: dict) -> CheckReport:
    """Independent coverage: row-matching scans against the frozen graph
    (coverage by name scan, deps by element-wise comparison, alts by
    element-wise comparison), plus the weak-outline adverse witness."""

    reasons: List[str] = []
    graph = (("main-claim", ("ex-contract", "ex-performance"), ()),
             ("best-rebuttal", ("ex-causation",), ()),
             ("weak-rebuttal-a", ("ex-timing",), ()),
             ("weak-rebuttal-b", (), ()),
             ("primary-theory", ("ex-contract",),
              ("fallback-theory",)))

    def covers(outline):
        covered = outline.get("covered", [])
        deps_kept = outline.get("deps_kept", {})
        alts_kept = outline.get("alts_kept", {})
        for (nid, deps, alts) in graph:
            found = False
            c = 0
            while c < len(covered):
                if covered[c] == nid:
                    found = True
                c += 1
            if not found:
                return False
            if nid not in deps_kept:
                return False
            kept = list(deps_kept[nid])
            if len(kept) != len(deps):
                return False
            d = 0
            while d < len(deps):
                if kept[d] != deps[d]:
                    return False
                d += 1
            if len(alts) == 0:
                continue
            if nid not in alts_kept:
                return False
            ka = list(alts_kept[nid])
            if len(ka) != len(alts):
                return False
            a = 0
            while a < len(alts):
                if ka[a] != alts[a]:
                    return False
                a += 1
        return True

    outline = claimed.get("outline", {})
    if covers(outline) is not True:
        reasons.append("the claimed outline must cover the frozen graph")
    if claimed.get("covers_frozen") is not covers(outline):
        reasons.append("coverage verdict differs from the row scan")

    weak = {
        "covered": ["main-claim", "weak-rebuttal-a", "weak-rebuttal-b"],
        "deps_kept": {
            "main-claim": ["ex-contract", "ex-performance"],
            "weak-rebuttal-a": ["ex-timing"],
            "weak-rebuttal-b": [],
        },
        "alts_kept": {},
    }
    if claimed.get("weak_outline_fails") is not (not covers(weak)):
        reasons.append("the weak outline must fail coverage")
    if claimed.get("weak_count_three") is not (
            len(weak["covered"]) == 3):
        reasons.append("the weak outline covers exactly three ids")
    if claimed.get("count_is_not_coverage") is not (
            len(weak["covered"]) == 3 and not covers(weak)):
        reasons.append("three covered ids do not establish coverage")
    if claimed.get("best_rebuttal_missing") is not (
            "best-rebuttal" not in weak["covered"]):
        reasons.append("the best rebuttal is missing from the weak outline")
    return CheckReport(not reasons, reasons)


