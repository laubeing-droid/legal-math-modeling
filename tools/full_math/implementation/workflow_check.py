# D116 — exact gap by index scan
# ---------------------------------------------------------------------------

def check_D116(required: Sequence[str], vdr: Sequence[str],
               claimed: dict) -> CheckReport:
    """Independent gap: scan the required list by index, keep the row
    when a full scan of the room catalog misses it; verify the exact
    iff-characterization row by row over required ∪ room, the pending
    conversion (name, status) row by row, and the ALL_134 witness
    (litigation-search required, only charter in the room)."""

    reasons: List[str] = []
    gap: List[str] = []
    i = 0
    while i < len(required):
        d = required[i]
        hit = False
        j = 0
        while j < len(vdr):
            if vdr[j] == d:
                hit = True
                break
            j += 1
        if not hit:
            gap.append(d)
        i += 1
    if claimed.get("missing") != gap:
        reasons.append("missing list differs from the index-scan gap")

    pending: List[Tuple[str, str]] = []
    k = 0
    while k < len(gap):
        pending.append((gap[k], "pending"))
        k += 1
    if claimed.get("pending") != pending:
        reasons.append("pending rows differ from the independent conversion")

    universe: List[str] = []
    for d in list(required) + list(vdr):
        if d not in universe:
            universe.append(d)
    exact_ok = True
    for d in universe:
        in_req = d in required
        in_room = d in vdr
        expect = in_req and not in_room
        if (d in gap) is not expect:
            exact_ok = False
    if claimed.get("gap_exact") is not exact_ok:
        reasons.append("the gap must be exactly required minus room")

    conv_ok = True
    m = 0
    while m < len(gap):
        if (gap[m], "pending") not in pending:
            conv_ok = False
        m += 1
    if claimed.get("missing_become_pending") is not conv_ok:
        reasons.append("every missing document must become a pending row")
    if claimed.get("no_silent_drop") is not (len(pending) == len(gap)):
        reasons.append("no missing document may be silently dropped")

    # the ALL_134 witness is input-independent: litigation-search
    # required, only charter in the room
    if claimed.get("witness_missing") != ["litigation-search"]:
        reasons.append("the litigation-search witness must stay missing")
    if claimed.get("witness_missing_kept") is not True:
        reasons.append("the witness gap must keep the missing item")
    if claimed.get("witness_not_in_room") is not True:
        reasons.append("the missing item is not in the room")
    if claimed.get("fabricated_required_empty") is not (
            claimed.get("witness_missing") == ["litigation-search"]):
        reasons.append("echoing the room into required must yield no gap"
                       " only for the echoed list itself")
    if claimed.get("fabrication_cannot_erase") is not True:
        reasons.append("the room echo cannot erase the real missing item")
    return CheckReport(not reasons, reasons)


